// Подключение к базе и запросы от имени вошедшего — ровно так Supabase выполняет запрос пользователя: транзакция, роль authenticated,
// данные токена в request.jwt.claims (из них auth.uid() берёт sub). set local и set_config(…, true) живут до конца транзакции.
const DB_LIB = `import { Pool, type PoolClient } from "pg";

// Подключение к базе по DATABASE_URL из .env.local — от имени её владельца, и RLS на такие запросы не действует.
// Напрямую через pool ходит только вход (app/api/login), как сервис входа в Supabase; остальное — через asUser.
export const pool = new Pool({ connectionString: process.env.DATABASE_URL });

// Запросы от имени вошедшего — так их выполняет Supabase: роль authenticated, а auth.uid() в базе возвращает uid.
// Всё внутри fn идёт одной транзакцией, и какие строки видны, решают политики RLS.
export async function asUser<T>(uid: string, fn: (db: PoolClient) => Promise<T>): Promise<T> {
  const db = await pool.connect();
  try {
    await db.query("begin");
    await db.query("set local role authenticated");
    await db.query("select set_config('request.jwt.claims', $1, true)", [
      JSON.stringify({ sub: uid, role: "authenticated" }),
    ]);
    const result = await fn(db);
    await db.query("commit");
    return result;
  } catch (err) {
    await db.query("rollback");
    throw err;
  } finally {
    db.release();
  }
}
`

const SESSION_LIB = `import { createHmac, timingSafeEqual } from "node:crypto";
import { cookies } from "next/headers";

// Сессия — cookie «uid.подпись». Подпись — HMAC-SHA256 с секретом SESSION_SECRET из .env.local:
// без секрета чужой uid в cookie не подставить. httpOnly — JavaScript страницы cookie не прочитает.
const COOKIE = "session";

function sign(uid: string): string {
  const secret = process.env.SESSION_SECRET;
  if (!secret) throw new Error("Не задан SESSION_SECRET");
  return createHmac("sha256", secret).update(uid).digest("base64url");
}

// После входа: cookie с подписанным uid
export async function startSession(uid: string) {
  (await cookies()).set(COOKIE, \`\${uid}.\${sign(uid)}\`, {
    httpOnly: true,
    sameSite: "lax",
    secure: process.env.NODE_ENV === "production",
    path: "/",
  });
}

// Кто вошёл: uid из cookie, если подпись верна, иначе null
export async function currentUser(): Promise<string | null> {
  const [uid, signature] = ((await cookies()).get(COOKIE)?.value ?? "").split(".");
  if (!uid || !signature) return null;
  const expected = Buffer.from(sign(uid));
  const actual = Buffer.from(signature);
  return actual.length === expected.length && timingSafeEqual(actual, expected) ? uid : null;
}
`

