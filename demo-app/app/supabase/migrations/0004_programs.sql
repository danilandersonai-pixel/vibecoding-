-- Программы тренировок: библиотека упражнений, программа тренера (шаблон) и тренировки по шаблону.
-- Строка тренировки ссылается на строку шаблона: упражнение, подходы и повторы берутся из шаблона.

-- Библиотека упражнений — общая для всех тренеров
create table exercises (
  id bigint generated by default as identity primary key,
  name text not null unique
);

insert into exercises (name) values
  ('Присед'),
  ('Жим лёжа'),
  ('Тяга'),
  ('Подтягивания');

-- Программа тренера: название, например «Ноги, 4 недели»
create table programs (
  id bigint generated by default as identity primary key,
  coach_id uuid not null references profiles (id),
  title text not null
);

-- Строка шаблона: упражнение из библиотеки, подходы × повторы
create table program_items (
  id bigint generated by default as identity primary key,
  program_id bigint not null references programs (id) on delete cascade,
  exercise_id bigint not null references exercises (id),
  sets int not null check (sets > 0),
  reps int not null check (reps > 0)
);

-- Строка тренировки по шаблону — ссылка на строку шаблона. Удалили строку шаблона — удаляется и она: строк без шаблона не остаётся
create table workout_items (
  id bigint generated by default as identity primary key,
  workout_id bigint not null references workouts (id) on delete cascade,
  program_item_id bigint not null references program_items (id) on delete cascade
);

-- Подход — к строке тренировки (необязательно): удалили строку — удаляются и её подходы
alter table sets add column workout_item_id bigint references workout_items (id) on delete cascade;

-- Упражнения тренировки для страницы: упражнение, подходы и повторы — из строки шаблона.
-- security_invoker — вид читает таблицы с правами того, кто спрашивает, поэтому RLS действует так же, как на самих таблицах
create view workout_exercises with (security_invoker = true) as
  select wi.id, wi.workout_id, e.name as exercise, pi.sets, pi.reps
    from workout_items wi
    join program_items pi on pi.id = wi.program_item_id
    join exercises e on e.id = pi.exercise_id;

-- RLS на новых таблицах, как в 0002_rls.sql: политики — для вошедших (authenticated), без входа не видно ничего
alter table exercises enable row level security;
alter table programs enable row level security;
alter table program_items enable row level security;
alter table workout_items enable row level security;

-- Библиотеку видят все вошедшие
create policy "библиотека для всех" on exercises
  for select to authenticated using (true);

-- Программы и их строки: тренер видит, создаёт, меняет и удаляет свои
create policy "тренер ведёт свои программы" on programs
  for all to authenticated
  using (coach_id = auth.uid())
  with check (coach_id = auth.uid());
create policy "тренер ведёт строки программ" on program_items
  for all to authenticated
  using (program_id in (select id from programs where coach_id = auth.uid()))
  with check (program_id in (select id from programs where coach_id = auth.uid()));
-- подопечный видит строки шаблона своих тренировок: из них берутся его упражнения
create policy "подопечный видит строки шаблона" on program_items
  for select to authenticated using (id in (
    select wi.program_item_id from workout_items wi join workouts w on w.id = wi.workout_id
      join clients c on c.id = w.client_id where c.user_id = auth.uid()));

-- Строки тренировок: тренер — у своих подопечных, подопечный — свои
create policy "тренер видит строки тренировок" on workout_items
  for select to authenticated using (workout_id in (
    select w.id from workouts w join clients c on c.id = w.client_id where c.coach_id = auth.uid()));
create policy "тренер добавляет строки" on workout_items
  for insert to authenticated with check (workout_id in (
    select w.id from workouts w join clients c on c.id = w.client_id where c.coach_id = auth.uid()));
create policy "подопечный видит свои строки" on workout_items
  for select to authenticated using (workout_id in (
    select w.id from workouts w join clients c on c.id = w.client_id where c.user_id = auth.uid()));
