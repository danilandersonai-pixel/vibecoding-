-- Модель данных первой версии (docs/spec.md): тренер, подопечный, тренировка, подход.
-- Пользователи с паролями — в auth.users (их ведёт Supabase), здесь — то, что о них знает приложение.

-- Профиль: тренер или подопечный. id тот же, что у пользователя в auth.users
create table profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null check (role in ('coach', 'client')),
  name text not null
);

-- Подопечный тренера coach_id. user_id — его вход в приложение
create table clients (
  id bigint generated by default as identity primary key,
  coach_id uuid not null references profiles (id),
  user_id uuid unique references profiles (id),
  name text not null
);

-- Тренировка подопечного: название и день
create table workouts (
  id bigint generated by default as identity primary key,
  client_id bigint not null references clients (id),
  title text not null,
  day date not null
);

-- Подход: вес и повторы, оба больше нуля
create table sets (
  id bigint generated by default as identity primary key,
  workout_id bigint not null references workouts (id),
  weight numeric not null check (weight > 0),
  reps int not null check (reps > 0)
);
