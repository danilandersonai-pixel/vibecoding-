type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-log',
      t.beat('s2-log', 5) + 110, // все четыре карточки на месте
      end('s2-log') - 14,
      LAST_BOX,
      'Последние 30%',
      'Что обычно остаётся после быстрых 70% — список вопросов к своему проекту. Обработка ошибок: пропала связь, чужой сервис ответил ошибкой 500, файл пуст — иначе приложение падает у человека. Необычные случаи: пустые списки, разные алфавиты, часовые пояса, двое жмут «Купить» одновременно — иначе данные тихо портятся. Безопасность: права доступа, проверка ввода, никаких паролей и ключей в коде. Скорость: один запрос к базе вместо сотен одинаковых, поиск по индексам. Чужие сервисы — по их настоящим правилам, а не придуманным ИИ. Эксплуатация: журналы, показатели, оповещения о сбоях, откат. Поддерживаемость: единые правила, без дублей.',
    ),
    spot(
      's3-symptoms',
      t.beat('s3-symptoms', 3) + 130, // Марина, новичок и ответ ИИ на месте
      t.beat('s3-symptoms', 5) - 8,
      PARADOX_BOX,
      'Парадокс знаний',
      'ИИ полезнее тому, кто уже понимает, что проверять: опытный разработчик видит неверное решение почти сразу, новичок принимает его целиком. Разрыв сокращают два приёма. В начале сессии попросите агента рассказать, что в проекте уже сделано. А прежде чем считать работу законченной, спросите: «Что сломается в моём приложении на необычных данных? Перечисли».',
    ),
    spot(
      's4-practice',
      t.beat('s4-practice', 6) + 30, // обе схемы на месте, лесенка растёт
      end('s4-practice') - 14,
      SCHEMES_BOX,
      'Две схемы работы',
      'Запуск с нуля (bootstrap): из идеи, макета или наброска ИИ за часы собирает рабочий прототип — так работают конструкторы приложений и вайб-кодинг. Идеи проверяются быстро, но в продукт прототип нередко переписывают. Итерации в существующем проекте: подсказки при наборе, тесты, наведение порядка в коде, объяснение чужого кода, изменения базы. В процентах выигрыш меньше, зато он копится и почти не оставляет долга: каждое изменение проверяет человек.',
    ),
    spot(
      's5-step',
      t.beat('s5-step', 1) + 40, // все десять правил на месте
      t.beat('s5-step', 4) - 8,
      RULES_BOX,
      'Десять золотых правил',
      '1. Принимайте только то, что можете объяснить коллеге. 2. Маленькие шаги: задача — проверяемый результат — коммит. 3. Перед экспериментом — коммит рабочей версии. 4. Способ проверки — до работы, лучше в виде теста. 5. Ищите причину: ошибка, спрятанная молчаливым try/catch или отключённой проверкой, не исправлена. 6. Две неудачные попытки — меняйте подход. 7. Устройство проекта выбираете вы из вариантов ИИ. 8. Ключи и пароли — в переменных окружения и хранилищах секретов; утёкший ключ замените. 9. После задачи спросите, какие файлы изменены и зачем. 10. Прототип — не продукт: перед выходом к людям пройдите чек-лист последних 30%.',
    ),
    spot(
      's5-step',
      t.beat('s5-step', 5) + 60, // строка с удалённой проверкой подсвечена
      end('s5-step') - 14,
      DIFF_BOX,
      'Как читать дифф',
      'Дифф — что изменилось в файле. Минус и красный фон — строка ушла, плюс и зелёный — строка новая, серые не тронуты и нужны для ориентира. По каждой удалённой строке спросите ИИ, зачем она убрана и что без неё изменится; ответ неясен — правку не принимайте. В десктопном приложении дифф открывает значок «+ −» под ответом Claude, а к строке можно оставить комментарий.',
    ),
    spot(
      's6-rollback',
      t.beat('s6-rollback', 1) + 150, // точки и варианты отката на месте
      t.beat('s6-rollback', 3) - 8,
      POINTS_BOX,
      'Контрольные точки',
      'Перед каждым вашим запросом Claude Code запоминает состояние файлов. /rewind или двойное нажатие Esc в пустом поле ввода открывают список точек: вернуть можно код, беседу или и то и другое. Но точки отменяют только правки Claude в файлах — команды в терминале, изменения в базе данных и выкладка сайта остаются как есть. Перед рискованным шагом сохраняйтесь коммитом.',
    ),
  ]
}

