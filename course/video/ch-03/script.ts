type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-log',
      t.beat('s2-log', 5) + 110, // все четыре карточки на месте
      end('s2-log') - 14,
      LAST_BOX,
      'Последние 30%',
      'Семь областей, которые проверяют после быстрых 70%. Ошибки: что будет, если в зале пропал интернет, чужой сервис ответил кодом 500 или пришёл пустой файл? Иначе приложение упадёт прямо у Анны. Необычные случаи: пустой журнал, имена на разных алфавитах, часовые пояса, два одновременных нажатия — иначе данные незаметно испортятся. Безопасность: кто что может видеть, проверка ввода, ни одного пароля или ключа в коде. Скорость: один запрос к базе вместо сотни одинаковых, индексы для поиска. Чужие сервисы — по их настоящей документации, а не по догадкам ИИ. Эксплуатация: журнал работы, показатели, сигнал о сбое, путь назад. Поддерживаемость: общие правила и никаких копий одного и того же кода.',
    ),
    spot(
      's3-symptoms',
      t.beat('s3-symptoms', 3) + 130, // Марина, новичок и ответ ИИ на месте
      t.beat('s3-symptoms', 5) - 8,
      PARADOX_BOX,
      'Парадокс знаний',
      'Чем лучше вы понимаете, что проверять, тем больше выигрываете от ИИ: Марина замечает забытые повторы в формуле объёма за пару секунд, а новичок пропустит такой ответ как есть. Разрыв сокращают два приёма. Открыв новую сессию, первым делом попросите агента коротко пересказать, что уже готово в журнале тренировок. А перед тем как назвать работу законченной, спросите его: «На каких странных данных мой журнал сломается? Дай список».',
    ),
    spot(
      's4-practice',
      t.beat('s4-practice', 6) + 30, // обе схемы на месте, лесенка растёт
      end('s4-practice') - 14,
      SCHEMES_BOX,
      'Две схемы работы',
      'Первая схема — запуск с нуля (bootstrap). Из идеи, макета или наброска ИИ за несколько часов собирает действующий прототип; на этом построены вайб-кодинг и конструкторы приложений. Идею так проверяют быстро, но превращать прототип в продукт часто приходится через переписывание. Вторая — итерации в проекте, который уже есть: ИИ каждый день помогает с мелким — дописывает строку на лету, пишет тесты, прибирает код, растолковывает чужой код, меняет базу данных. Каждый такой шаг даёт немного, зато выгода копится, а долгов почти не остаётся: каждую правку смотрит человек.',
    ),
    spot(
      's5-step',
      t.beat('s5-step', 1) + 40, // все десять правил на месте
      t.beat('s5-step', 4) - 8,
      RULES_BOX,
      'Десять золотых правил',
      '1. Берите в проект только то, что сможете объяснить коллеге. 2. Маленькие шаги: задача за задачей, у каждой — проверяемый итог и свой коммит. 3. Перед каждым экспериментом — коммит рабочей версии. 4. Как поймёте, что получилось, решите до начала, а лучше закрепите тестом. 5. Устраняйте причину: ошибка, заглушённая пустым try/catch или выключенной проверкой, никуда не делась. 6. Две попытки не помогли — смените подход. 7. Как устроен проект, выбираете вы из нескольких вариантов ИИ. 8. Ключи и пароли живут в переменных окружения и хранилищах секретов; попавший в чат ключ сразу меняйте. 9. После задачи пусть агент перечислит изменённые файлы и объяснит зачем. 10. Прототип ещё не продукт: до встречи с настоящими пользователями проверьте все области последних 30%.',
    ),
    spot(
      's5-step',
      t.beat('s5-step', 5) + 60, // строка с удалённой проверкой подсвечена
      end('s5-step') - 14,
      DIFF_BOX,
      'Как читать дифф',
      'Дифф — что изменилось в файле. Минус и красный фон — строка ушла, плюс и зелёный — строка новая, серые не тронуты и нужны для ориентира. По каждой удалённой строке спросите ИИ, зачем она убрана и что без неё изменится; ответ неясен — правку не принимайте. В десктопном приложении дифф открывает значок «+ −» под ответом Claude, а к строке можно оставить комментарий.',
    ),
    spot(
      's6-rollback',
      t.beat('s6-rollback', 1) + 150, // точки и варианты отката на месте
      t.beat('s6-rollback', 3) - 8,
      POINTS_BOX,
      'Контрольные точки',
      'Claude Code сам ставит отметку состояния файлов перед каждой вашей просьбой. Список отметок открывает команда /rewind, а ещё Esc, нажатый дважды, пока поле ввода пустое. Откатить можно только правки в коде, только переписку или всё вместе. Но отметки возвращают лишь файлы, которые менял Claude: запущенная в терминале команда, записи в базе данных и выложенный сайт так и останутся. Поэтому перед опасным шагом — скажем, переделкой таблицы с подходами Анны — сначала сделайте коммит.',
    ),
  ]
}

