export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-autopilot')
  const s3 = b('s3-intent')
  const s2 = b('s2-cost')
  const s4 = b('s4-model')
  const s5 = b('s5-bench')
  const s6 = b('s6-pay')
  return {
    's1-autopilot': {
      transition: 'fade',
      camera: [
        // самолёт в небе крупно → весь кадр со шкалой → лёгкий наезд на посадку
        key(0, SHOT.s1sky),
        key(s1(1) - 6, SHOT.s1sky),
        key(s1(1) + 26, SHOT.whole),
        key(s1(6) - 6, SHOT.whole),
        key(s1(6) + 24, SHOT.s1final),
      ],
    },
    's2-cost': {
      transition: 'slide',
      camera: [
        // схема режимов по центру (горячая точка «Зона риска») → весь кадр с иллюзией готовности
        // → цена ошибки и корзины на доске 2
        key(0, SHOT.s2chart),
        key(s2(2) - 6, SHOT.s2chart),
        key(s2(2) + 24, SHOT.whole),
        key(s2(3) - 6, SHOT.whole),
        key(s2(3) + 30, SHOT.board2),
      ],
    },
    's3-intent': {
      transition: 'zoom',
      camera: [
        // пробелы и чат → наезд на запрос с намерением → четыре навыка на доске 2
        key(0, SHOT.s3left),
        key(s3(2) - 6, SHOT.s3left),
        key(s3(2) + 24, SHOT.s3prompt),
        key(s3(5) - 6, SHOT.s3prompt),
        key(s3(5) + 30, SHOT.board2),
      ],
    },
    's4-model': {
      transition: 'slide',
      camera: [
        // инструменты и модель → этикетка и карточка (горячая точка) → линейка Claude на доске 3
        key(0, SHOT.whole),
        key(s4(2) - 6, SHOT.whole),
        key(s4(2) + 30, SHOT.board2),
        key(s4(6) - 6, SHOT.board2),
        key(s4(6) + 30, SHOT.board3),
      ],
    },
    's5-bench': {
      transition: 'zoom',
      camera: [
        // таблица лидеров крупнее → весь кадр с ловушками → пирамида и мини-набор (горячая точка)
        key(0, SHOT.s5board),
        key(s5(1) - 6, SHOT.s5board),
        key(s5(1) + 24, SHOT.whole),
        key(s5(7) - 6, SHOT.whole),
        key(s5(7) + 30, SHOT.board2),
      ],
    },
    's6-pay': {
      transition: 'fade',
      camera: [
        // абонемент и счётчик → лимиты (горячая точка) → наезд на итог
        key(0, SHOT.whole),
        key(s6(3) - 6, SHOT.whole),
        key(s6(3) + 30, SHOT.board2),
        key(s6(6) - 6, SHOT.board2),
        key(s6(6) + 24, SHOT.s6recap),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const risk0 = plotAt(RISK.fx0, RISK.fy0)
  const risk1 = plotAt(RISK.fx1, RISK.fy1)
  const benchEnd = t.sceneEnd('s5-bench') - t.abs('s5-bench', 0)
  return [
    spot(
      's2-cost',
      t.beat('s2-cost', 1) + 30, // зона риска уже закрашена
      t.beat('s2-cost', 2) - 6,
      { x: risk0.x, y: risk0.y, w: risk1.x - risk0.x, h: risk1.y - risk0.y },
      'Зона риска',
      'Вайб-кодинг: ИИ пишет почти весь код, а человек его почти не читает и проверяет только поведение. Годится для прототипов, личных утилит и экспериментов. Главный риск — код, который никто не может чинить и развивать.',
    ),
    spot(
      's4-model',
      t.beat('s4-model', 3) + 20, // карточка уже на месте
      t.beat('s4-model', 6) - 6,
      { x: S4.card.x, y: S4.card.y, w: S4.card.w, h: CARD_H },
      'Карточка модели',
      'Документ, который компания публикует вместе с моделью (у Anthropic и OpenAI — system card): тесты, безопасность и известные ограничения. Карточки Claude — на anthropic.com/system-cards, цены и характеристики — на странице модели в документации.',
    ),
    spot(
      's5-bench',
      t.beat('s5-bench', 8) + 20, // мини-набор уже появился
      benchEnd - 12,
      { x: S5.mini.x, y: S5.mini.y, w: S5.mini.w, h: checklistHeight(5) },
      'Мини-набор',
      '5–10 задач из вашей работы: пара простых, пара средних, одна-две трудные. У каждой — критерий «готово». Один и тот же запрос — разным моделям в одинаковых условиях; считайте, сколько решено с первой попытки и сколько понадобилось правок.',
    ),
    spot(
      's6-pay',
      t.beat('s6-pay', 3) + 40, // кольцо и недельная полоса уже видны
      t.beat('s6-pay', 5) + 20,
      S6.limits,
      'Лимиты Claude',
      'Сессионный лимит обновляется скользящим окном в пять часов, на платных тарифах поверх него действует недельный. Чат и Claude Code тратят общий лимит. Остаток — в Settings → Usage или по команде /usage.',
    ),
  ]
}

