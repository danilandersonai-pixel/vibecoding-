export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-taste')
  const s2 = b('s2-line')
  const s3 = b('s3-collect')
  const s4 = b('s4-describe')
  const s5 = b('s5-build')
  const s6 = b('s6-traps')
  const s7 = b('s7-passes')
  return {
    's1-taste': {
      transition: 'fade',
      camera: [
        // повар в ресторане крупно → весь кадр со своей кухней → прямой и обратный путь на доске 2
        key(0, SHOT.s1near),
        key(s1(2) - 6, SHOT.s1near),
        key(s1(2) + 24, SHOT.whole),
        key(s1(3) - 6, SHOT.whole),
        key(s1(3) + 30, SHOT.board2),
      ],
    },
    's2-line': {
      transition: 'slide',
      camera: [
        // можно и нельзя → шкала (горячая точка «Функциональный аналог») → три рамки
        key(0, SHOT.whole),
        key(s2(2) - 6, SHOT.whole),
        key(s2(2) + 30, SHOT.board2),
        key(s2(5) - 6, SHOT.board2),
        key(s2(5) + 30, SHOT.board3),
      ],
    },
    's3-collect': {
      transition: 'zoom',
      camera: [
        // пять шагов и стена (горячая точка) → материал → разбор по слоям
        key(0, SHOT.whole),
        key(s3(2) - 6, SHOT.whole),
        key(s3(2) + 30, SHOT.board2),
        key(s3(5) - 6, SHOT.board2),
        key(s3(5) + 30, SHOT.board3),
      ],
    },
    's4-describe': {
      transition: 'slide',
      camera: [
        // спецификация крупнее → весь кадр с корзинами (горячая точка «Своё отличие») → проверка и стена
        key(0, SHOT.s4near),
        key(s4(1) - 6, SHOT.s4near),
        key(s4(1) + 24, SHOT.whole),
        key(s4(6) - 6, SHOT.whole),
        key(s4(6) + 30, SHOT.board2),
      ],
    },
    's5-build': {
      transition: 'zoom',
      camera: [
        // новая сессия крупнее → весь кадр с дизайном → таблица паритета (горячая точка) и два приложения
        key(0, SHOT.s5near),
        key(s5(1) + 30, SHOT.s5near),
        key(s5(1) + 60, SHOT.whole),
        key(s5(3) - 6, SHOT.whole),
        key(s5(3) + 30, SHOT.board2),
      ],
    },
    's6-traps': {
      transition: 'fade',
      camera: [
        // две первые ловушки крупно → третья и четвёртая крупно → все семь карточек
        key(0, SHOT.s6near),
        key(s6(2) - 6, SHOT.s6near),
        key(s6(2) + 24, SHOT.s6right),
        key(s6(4) - 6, SHOT.s6right),
        key(s6(4) + 24, SHOT.whole),
      ],
    },
    's7-passes': {
      transition: 'zoom',
      camera: [
        // проект и карта → сценарий и описание на доске 2 → наезд на итог
        key(0, SHOT.whole),
        key(s7(2) - 6, SHOT.whole),
        key(s7(2) + 30, SHOT.board2),
        key(s7(5) - 6, SHOT.board2),
        key(s7(5) + 24, SHOT.s7recap),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const binX = S4.bins[1]
  return [
    spot(
      's2-line',
      t.beat('s2-line', 3) + 30, // наше приложение уже встало на деление
      t.beat('s2-line', 4) + 40,
      S2.analog,
      'Функциональный аналог',
      'Умеет то же, что эталон, но код, название, тексты и оформление у него собственные. Авторское право по ст. 1259 ГК РФ не защищает идеи, методы и способы — только конкретную форму. Собираетесь зарабатывать на приложении по мотивам известного сервиса — покажите замысел юристу ещё до выхода.',
    ),
    spot(
      's3-collect',
      t.beat('s3-collect', 1) + 60, // описание уже прошло сквозь щель
      t.beat('s3-collect', 2) - 6,
      S3.wallSpot,
      'Стена чистой комнаты',
      'В начале 1980-х Compaq делала компьютер, совместимый с IBM PC. Часть её инженеров разбиралась, как устроена BIOS — программа IBM, отвечающая за управление компьютером, — и записывала это текстом. Другая часть кода IBM в глаза не видела и писала свою программу только по этим записям. Такой подход и называют «чистой комнатой». У вас стена стоит между третьим и четвёртым шагом: сквозь неё проходит лишь спецификация.',
    ),
    spot(
      's4-describe',
      t.beat('s4-describe', 4) + 40, // карточка отличия уже в корзине
      t.beat('s4-describe', 5) + 60,
      { x: binX, y: S4.binY, w: S4.binW, h: S4.binH },
      'Своё отличие',
      'Копировать эталон целиком бессмысленно: зрелый продукт годами обрастал сотнями функций. Для старта хватит главного — того, что нужно почти каждому, — плюс одна причина уйти к вам от конкурента. Где её искать: в отзывах на эталоны, среди жалоб, которые повторяются чаще остальных.',
    ),
    spot(
      's5-build',
      t.beat('s5-build', 3) + 110, // все строки таблицы уже на месте
      t.beat('s5-build', 4) + 100,
      { x: S5.table.x, y: S5.table.y, w: S5.table.w, h: TABLE_HEAD + 4 * TABLE_ROW },
      'Таблица паритета',
      'Список возможностей эталона и отметка, что из них уже есть у вас, с решением по каждой: готово, наше отличие, позже или не делаем. ИИ можно попросить составить её по спецификации и разбору, написать сквозной тест на каждый сценарий и перечислить места, где ваше поведение отличается без явного решения.',
    ),
  ]
}

