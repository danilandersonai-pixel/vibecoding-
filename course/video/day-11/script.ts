export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-build')
  const s2 = b('s2-pitfall')
  const s3 = b('s3-check')
  return {
    's1-build': {
      transition: 'fade',
      camera: [
        // тренировка Анны крупнее → весь кадр с Мариной и уведомлениями → доска 2: функция целиком (горячая точка)
        key(0, SHOT.s1close),
        key(s1(2) - 8, SHOT.s1close),
        key(s1(2) + 22, SHOT.whole),
        key(s1(5) - 4, SHOT.whole),
        key(s1(5) + 28, SHOT.board2),
      ],
    },
    's2-pitfall': {
      transition: 'slide',
      camera: [
        // агент и таблица без RLS крупнее → весь кадр с лентой Олега и политикой (горячая точка) → доска 2: уведомления (горячая точка)
        key(0, SHOT.s2right),
        key(s2(1) - 8, SHOT.s2right),
        key(s2(1) + 22, SHOT.whole),
        key(s2(6), SHOT.whole),
        key(s2(6) + 30, SHOT.board2),
      ],
    },
    's3-check': {
      transition: 'zoom',
      camera: [
        // чек-лист крупнее → весь кадр с браузером под чужим входом и тестами (горячая точка)
        key(0, SHOT.s3list),
        key(s3(1) - 8, SHOT.s3list),
        key(s3(1) + 22, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's1-build',
      t.beat('s1-build', 5) + 170, // все три слоя с подписями на месте
      end('s1-build') - 14,
      LAYERS_BOX,
      'Комментарии целиком',
      'Снизу вверх. Таблица comments: к какой тренировке, кто автор, текст и время. Правила доступа — в самой базе: кто читает и кто пишет. Наверху — поле и кнопка «Отправить». Комментарий показывайте как обычный текст: тогда вписанный в него код не выполнится у других (это XSS). У уведомлений своя таблица: кому, о чём, прочитано ли.',
    ),
    spot(
      's2-pitfall',
      t.beat('s2-pitfall', 5) + 90, // политика набрана, RLS включён, лента Олега уже без чужого
      t.beat('s2-pitfall', 6) - 6,
      POLICY_BOX,
      'Правило для комментариев',
      'Первые две строки включают RLS для таблицы. Дальше политика на чтение: комментарий виден, если он к тренировке, где вошедший (auth.uid()) — подопечный или тренер. На запись нужна своя политика: только в свою тренировку и от своего имени. У таблицы уведомлений тоже должен быть RLS: там текст комментариев.',
    ),
    spot(
      's2-pitfall',
      t.beat('s2-pitfall', 11) + 80, // четыре правила на месте, телефоны Марины и Димы — уже после правил
      end('s2-pitfall') - 14,
      RULES_BOX,
      'Правила уведомлений',
      'Подходы собираются в одно уведомление после тренировки. Тихие часы считают по часовому поясу получателя: ночное уведомление ждёт утра. В настройках каждый сам выбирает, о чём ему сообщать. Комментарий приходит отдельно и сразу — если не ночь. Это решения о продукте: попросите у ИИ два-три варианта, выберите и закрепите тестом.',
    ),
    spot(
      's3-check',
      t.beat('s3-check', 6) + 60, // все шесть пунктов отмечены
      end('s3-check') - 14,
      LIST_BOX,
      'Проверка чужим входом',
      'Нужны два тестовых входа у разных тренеров. Под чужим откройте ленту и прямой адрес тренировки: пусто — правило работает, видно — защиты нет. Закрепите это тестом на тестовой базе: чужому — пусто, тренеру — виден. Security Advisor в Supabase замечает таблицы без RLS и пишет об этом — такие письма не пропускайте.',
    ),
  ]
}

