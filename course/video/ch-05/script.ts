type Rect = { x: number; y: number; w: number; h: number }

/** Плашки проходов сцены 2 закреплены поверх камеры — их рамка сразу в координатах кадра. */
const TABS_BOX: Rect = { x: S2.tabs.xs[0] - 10, y: S2.tabs.y - 8, w: S2.tabs.xs[3] + S2.tabs.w - S2.tabs.xs[0] + 20, h: S2.tabs.h + 16 }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string, fixed = false): VideoHotspot => {
    const s = fixed ? r : toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  const cardsH = 3 * S3.cards.h + 2 * S3.cards.gap
  const [bottom, , top] = S7.tiers
  return [
    spot(
      's2-passes',
      t.beat('s2-passes', 6) + 12, // все четыре прохода пройдены
      end('s2-passes') - 14,
      TABS_BOX,
      'Четыре прохода',
      'Чужое изменение просматривают четыре раза, и каждый раз глубже. Обзор: список задетых файлов и всё лишнее сверх задачи — настройки, новые библиотеки, выключенные проверки. Интерфейс: что функция принимает, что возвращает, какие ошибки может выдать и что делает попутно, например пишет в файл. Трассировка: пройти руками живой сценарий с определёнными числами, от первого шага до последнего. Края: пусто, очень много, «ничего», повтор, два нажатия одновременно. Объяснение ИИ полезно, но сверяйте его с тем, что увидели сами.',
      true,
    ),
    spot(
      's3-majority',
      t.beat('s3-majority', 3) + 70, // все три примера уже на месте
      t.beat('s3-majority', 4) - 6,
      { x: S3.chart.x - 8, y: S3.chart.y - 56, w: S3.cards.x + S3.cards.w - S3.chart.x + 16, h: Math.max(S3.chart.h, cardsH) + 64 },
      'Решение большинства',
      'Модель тянется к ответу, который попадался ей при обучении чаще других. Поэтому её ответы предсказуемы, но не обязательно лучшие для вас: популярный вариант бывает старым или придуман для других объёмов. Признаки: старые версии библиотек; тяжёлая библиотека ради того, что умеет язык; способ листать список, который тормозит на миллионах строк; лишняя работа в браузере вместо сервера; учебный вход без лимита попыток. Помогают правила проекта, точные версии и просьба дать несколько вариантов с плюсами и минусами.',
    ),
    spot(
      's4-trace',
      t.beat('s4-trace', 2) + 70, // все три пометки уже на месте
      t.beat('s4-trace', 3) - 6,
      { x: S4.markX - 24, y: S4.trace.y - 8, w: S4.notesX + 228 - S4.markX + 24, h: 40 + 16 + TRACE_LINES * TRACE_ROW + 16 },
      'Стектрейс',
      'След ошибки: цепочка вызовов, по которой ошибка поднялась наверх. Самая верхняя строка говорит, что произошло. Ниже найдите первую строку с файлом вашего проекта и номером строки — разбираться обычно надо там. Всё, что из папки node_modules, — код чужих библиотек, такие строки пропускают. ИИ отправляйте весь текст без сокращений, а не пересказ своими словами.',
    ),
    spot(
      's5-bisect',
      t.beat('s5-bisect', 3) + 50, // седьмой найден, кандидатов осталось один
      t.beat('s5-bisect', 4) - 6,
      { x: S5.x0 - S5.r - 20, y: S5.bracketY - 52, w: 7 * S5.dx + 2 * S5.r + 40, h: S5.countY + 26 - S5.bracketY + 52 },
      'Деление пополам',
      'Поломка появилась после ряда коммитов? Не проверяйте их по одному. Возьмите коммит посередине между последним рабочим и первым сломанным: работает — ищите среди более поздних, сломан — среди более ранних. Каждая проверка вдвое сужает круг подозреваемых. Команда git bisect сама выбирает, какой коммит проверить, вы только сообщаете результат. Запоминать её не обязательно: попросите агента найти коммит через git bisect и показать, что в нём поменялось.',
    ),
    spot(
      's6-refactor',
      t.beat('s6-refactor', 4) + 80, // цикл нарисован, первый круг пройден
      t.beat('s6-refactor', 5) - 6,
      { x: S6.loop.xs[0] - 10, y: S6.loop.y - 46, w: S6.loop.undoX + S6.loop.w - S6.loop.xs[0] + 20, h: S6.loop.commitY + S6.loop.h - S6.loop.y + 66 },
      'Безопасный рефакторинг',
      'Четыре правила. Тестов нет — сначала попросите тесты, которые закрепят нынешнее поведение. Порядок наводят отдельно от новых возможностей: один коммит меняет устройство, другой — поведение, иначе проверить их нельзя. Двигайтесь мелкими шагами: после каждого тесты зелёные — и коммит; покраснели — отменяют лишь последний шаг. Крупную перестройку начинают с плана: список шагов, ваше одобрение, затем шаги выполняются поочерёдно.',
    ),
    spot(
      's7-tests',
      t.beat('s7-tests', 4) + 70, // все три яруса подписаны
      t.beat('s7-tests', 5) - 6,
      { x: bottom.x - 10, y: top.y - 10, w: bottom.w + 20, h: bottom.y + bottom.h - top.y + 20 },
      'Пирамида тестов',
      'Внизу модульные: проверяют небольшую часть отдельно от остальных, их больше всего, и они быстрые. Посередине интеграционные: несколько частей сразу, скажем ваше приложение в паре с настоящей базой для тестов; их меньше, идут они дольше. Наверху сквозные: повторяют действия человека от входа до результата; таких тестов немного, работают они дольше всех, зато ближе всего к жизни. На любом уровне тесты пишут от требований, а не от готового кода.',
    ),
  ]
}

