/** Центры плашек ширины widths, уложенных в ряд с зазором gap: от левого края left или по центру center. */
export function packRow(widths: number[], gap: number, at: { left: number } | { center: number }): number[] {
  const total = widths.reduce((s, w) => s + w, 0) + Math.max(0, widths.length - 1) * gap
  let x = 'left' in at ? at.left : at.center - total / 2
  return widths.map((w) => {
    const c = x + w / 2
    x += w + gap
    return c
  })
}

