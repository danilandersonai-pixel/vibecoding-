export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-today')
  const s2 = b('s2-invite')
  const s3 = b('s3-forever')
  const s4 = b('s4-check')
  return {
    's1-today': {
      transition: 'fade',
      camera: [
        // Марина и ручное добавление крупнее → весь кадр (отъезд до реплики 2: места справа появляются уже на общем плане)
        key(0, SHOT.s1close),
        key(s1(1) - 36, SHOT.s1close),
        key(s1(1) - 6, SHOT.whole),
      ],
    },
    's2-invite': {
      transition: 'slide',
      camera: [
        // браузер Марины крупнее → весь путь приглашения (горячая точка) → сама ссылка крупно;
        // места справа и внизу появляются после отъезда, а наезд — когда остальное уже погасло
        key(0, SHOT.s2browser),
        key(s2(1) - 36, SHOT.s2browser),
        key(s2(1) - 6, SHOT.whole),
        key(s2(5) + 14, SHOT.whole),
        key(s2(5) + 44, SHOT.s2link),
      ],
    },
    's3-forever': {
      transition: 'zoom',
      camera: [
        // весь кадр с подписанными местами: чат, дверь, угаданный адрес → доска 2: исправление (горячая точка)
        key(0, SHOT.whole),
        key(s3(5) - 4, SHOT.whole),
        key(s3(5) + 30, SHOT.board2),
      ],
    },
    's4-check': {
      transition: 'fade',
      camera: [
        // проверки чуть крупнее → весь кадр (горячая точка) → доска 2: повторный аудит (горячая точка)
        key(0, SHOT.s4near),
        key(s4(1) - 6, SHOT.s4near),
        key(s4(1) + 20, SHOT.whole),
        key(s4(5) - 4, SHOT.whole),
        key(s4(5) + 28, SHOT.board2),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-invite',
      t.beat('s2-invite', 4) + 72, // весь путь нарисован: ссылка, телефон, запись в базе, правила доступа, замок
      t.beat('s2-invite', 5) - 6,
      FLOW_BOX,
      'Путь приглашения',
      'Путь короткий: кнопка у тренера → ссылка в мессенджере → вход подопечного → в базе появляется связь «Анна — подопечная Марины». После этого Анна есть в списке Марины, а у Анны — программа тренера. Правила доступа к строкам (RLS) не меняются: Анна видит только свои тренировки, тренер — только своих подопечных.',
    ),
    spot(
      's3-forever',
      t.beat('s3-forever', 8) + 84, // запись приглашения и все проверки сервера на месте, отказ показан
      end('s3-forever') - 14,
      LOCK_BOX,
      'Приглашение с замком',
      'В нашем примере приглашение — запись в базе: случайный код, тренер, срок и кто принял. Работает один раз и 48 часов — это выбор примера, а не правило. Тренера сервер берёт из записи: адрес пришёл извне, доверять ему нельзя. Марина видит свои приглашения и отзывает лишние. Если ссылку открыл не тот человек, это видно по полю «принял».',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 4) + 50, // все пять проверок отмечены
      t.beat('s4-check', 5) - 6,
      CHECKS_BOX,
      'Проверки приглашения',
      'Пять проверок руками: тестовый аккаунт принимает приглашение; та же ссылка второй раз — отказ; отозванное приглашение — отказ; ссылка старше 48 часов — отказ (это удобнее проверить тестом, чем ждать); новичок видит только свои тренировки. Попросите агента записать каждую проверку тестом — тогда будущая правка не сломает её тихо.',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 7) + 76, // вопросы, чат и тесты в терминале на месте
      end('s4-check') - 14,
      AUDIT_BOX,
      'Повторный аудит',
      'Вопросы главы 8 к приглашениям. Откуда данные: код из адреса — чужой ввод. Кто может вызвать: только вошедший. Что сделает злоумышленник: будет перебирать коды — нужны длинный случайный код и лимит попыток. Что в журналах: код ссылки туда не пишут. Права процесса — минимальные. Вне задачи ничего не поменялось? Код агент не трогает — только отчёт.',
    ),
  ]
}

