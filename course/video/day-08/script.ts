export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-week')
  const s2 = b('s2-sort')
  const s3 = b('s3-vague')
  const s4 = b('s4-check')
  return {
    's1-week': {
      transition: 'fade',
      camera: [
        // неделя и план дня крупнее → весь кадр: путь задачи через фонового агента
        key(0, SHOT.s1close),
        key(s1(1) - 6, SHOT.s1close),
        key(s1(1) + 24, SHOT.whole),
      ],
    },
    's2-sort': {
      transition: 'slide',
      camera: [
        // три отзыва крупнее → весь кадр со стопками (горячая точка) → первая стопка и агент
        key(0, SHOT.s2notes),
        key(s2(3) - 6, SHOT.s2notes),
        key(s2(3) + 24, SHOT.whole),
        key(s2(6) - 6, SHOT.whole),
        key(s2(6) + 24, SHOT.s2agent),
      ],
    },
    's3-vague': {
      transition: 'zoom',
      camera: [
        // расплывчатая задача и агент → весь кадр с пул-реквестом → доска 2: задача (горячая точка)
        key(0, SHOT.s3left),
        key(s3(2) - 6, SHOT.s3left),
        key(s3(2) + 24, SHOT.whole),
        key(s3(4) - 6, SHOT.whole),
        key(s3(4) + 28, SHOT.board2),
      ],
    },
    's4-check': {
      transition: 'fade',
      camera: [
        // что сделать у себя крупнее → весь кадр с облачной сессией и приёмкой (горячая точка)
        key(0, SHOT.s4left),
        key(s4(1) - 6, SHOT.s4left),
        key(s4(1) + 24, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-sort',
      t.beat('s2-sort', 5) + 30, // все три решения под стопками уже на месте
      t.beat('s2-sort', 6) - 6,
      STACKS_BOX,
      'Три стопки отзывов',
      'Первая стопка — то, что портит данные или ломает главный сценарий: это чинят первым. Вторая — то, что мешает людям каждый день. Третья — пожелания: они подождут. Кому что: если признак «готово» и тест можно написать заранее, задачу можно отдать агенту в фон. Размытую сначала проясняют с автором отзыва и ассистентом рядом, а потом отдают.',
    ),
    spot(
      's3-vague',
      t.beat('s3-vague', 6) + 70, // все четыре части задачи написаны
      end('s3-vague') - 14,
      TICKET_BOX,
      'Задача в четыре части',
      'Задача — одной фразой: что должно получиться. Контекст — где это в приложении и что похожее уже есть. Критерии готовности — признаки, которые можно проверить: значения, новые тесты, зелёные проверки. Ограничения — чего не трогать: старые тесты, схему базы, список библиотек. Не знаете, где это в коде, — пусть агент отыщет сам.',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 5) + 50, // все четыре пункта приёмки отмечены
      end('s4-check') - 14,
      ACCEPT_BOX,
      'Приёмка пул-реквеста',
      'Принять работу агента можно, не читая код. Сверьте его описание со своей задачей. Посмотрите список изменённых файлов: нет ли там настроек, старых тестов или базы, которых вы не просили трогать. Убедитесь, что проверки прошли и их не ослабили. Пройдите главный сценарий руками. Непонятно — спросите агента; ответ не устроил — не принимайте.',
    ),
  ]
}

