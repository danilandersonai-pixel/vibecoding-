export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-monday')
  const s2 = b('s2-build')
  const s3 = b('s3-empty')
  const s4 = b('s4-check')
  return {
    's1-monday': {
      transition: 'fade',
      camera: [
        // Марина и журнал крупно → весь кадр: места и карточки трёх вещей дня — после отъезда
        key(0, SHOT.s1close),
        key(s1(2) - 30, SHOT.s1close),
        key(s1(2), SHOT.whole),
      ],
    },
    's2-build': {
      transition: 'slide',
      camera: [
        // определения крупнее → весь кадр с пятницей и рекордом (горячая точка) → доска 2: отчёт
        key(0, SHOT.s2defs),
        key(s2(3) - 8, SHOT.s2defs),
        key(s2(3) + 22, SHOT.whole),
        key(s2(5) + 24, SHOT.whole),
        key(s2(5) + 54, SHOT.board2),
      ],
    },
    's3-empty': {
      transition: 'zoom',
      camera: [
        // весь кадр: записи из зала, отчёт и люди (горячая точка) → доска 2: правила и тесты
        key(0, SHOT.whole),
        key(s3(6) + 30, SHOT.whole),
        key(s3(6) + 60, SHOT.board2),
      ],
    },
    's4-check': {
      transition: 'fade',
      camera: [
        // список тестов крупнее → весь кадр с отчётом за неделю с пропуском (горячая точка)
        key(0, SHOT.s4tests),
        key(s4(4) - 8, SHOT.s4tests),
        key(s4(4) + 22, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-build',
      t.beat('s2-build', 4) + 40, // определения и вся таблица пятницы с итогом уже на месте
      t.beat('s2-build', 5) + 20,
      CALC_BOX,
      'Рекорд и объём',
      'Личный рекорд здесь — самый большой вес в упражнении, с которым сделан хоть один подход. Объём — сумма по подходам: повторы × вес. Пятница Анны: 5 × 52,5 = 262,5, ещё раз 262,5 и 3 × 55 = 165, вместе 690 кг. Такие определения записывают словами до кода: из них потом получаются тесты.',
    ),
    spot(
      's3-empty',
      t.beat('s3-empty', 5) + 120, // все три записи и оба сломанных поля отчёта уже на месте
      t.beat('s3-empty', 6) + 26,
      BROKEN_BOX,
      'Пустое поле и фунты',
      'Пустое поле, прочитанное как число, в JavaScript может дать NaN — «не число», и любая сумма с ним тоже NaN. Бывает тише: пустое становится нулём, и объём просто занижен. Фунты без единицы выглядят как килограммы: 135 фунтов ≈ 61,2 кг. Поэтому вес хранят с единицей, пустой вес не сохраняют, а у подтягиваний считают повторы.',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 4) + 40, // все шесть тестов отмечены, камера стоит
      end('s4-check') - 14,
      TESTS_BOX,
      'Тесты на расчёт',
      'Минимум для расчёта — три проверки: обычный случай, пустой и странный ввод. Здесь это пятница Анны (690 кг, рекорд 55), подход без веса, подтягивания, 135 фунтов и «52,5» с запятой. Тесты пишут по правилам, а не по готовому коду. А чтобы проверить сами тесты, сломайте расчёт нарочно: хороший тест покраснеет.',
    ),
  ]
}

