export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-build')
  const s2 = b('s2-pitfall')
  const s3 = b('s3-check')
  return {
    's1-build': {
      transition: 'fade',
      camera: [
        // Марина и листки крупно → весь кадр: библиотека, шаблон, цикл, календари (горячая точка) → доска 2: модель данных (горячая точка)
        key(0, SHOT.s1manual),
        key(s1(1) - 6, SHOT.s1manual),
        key(s1(1) + 24, SHOT.whole),
        key(s1(5) + 24, SHOT.whole),
        key(s1(5) + 54, SHOT.board2),
      ],
    },
    's2-pitfall': {
      transition: 'slide',
      camera: [
        // Анна и её прошлая неделя крупнее → весь кадр с шаблоном и ссылками (горячая точка) → доска 2: копия и версии (горячая точка)
        key(0, SHOT.s2anna),
        key(s2(1) - 6, SHOT.s2anna),
        key(s2(1) + 24, SHOT.whole),
        key(s2(5) + 30, SHOT.whole),
        key(s2(5) + 60, SHOT.board2),
      ],
    },
    's3-check': {
      transition: 'zoom',
      camera: [
        // чек-лист и телефон крупнее → весь кадр с правками шаблона → доска 2: тест (горячая точка), поломка и прогоны
        key(0, SHOT.s3list),
        key(s3(1) - 6, SHOT.s3list),
        key(s3(1) + 24, SHOT.whole),
        key(s3(3) - 6, SHOT.whole),
        key(s3(3) + 24, SHOT.board2),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's1-build',
      t.beat('s1-build', 4) + 100, // календарь Анны заполнен, всё остальное уже на месте
      t.beat('s1-build', 5) + 24,
      PROGRAM_BOX,
      'Программа тренировок',
      'Библиотека — общий список упражнений: каждое заводят один раз и дальше только выбирают. Шаблон собирают из библиотеки: упражнение, подходы, повторы. Цикл раскладывает шаблон по неделям — здесь 3×10, 3×8, 3×6, 3×5: повторов меньше, вес больше. Назначение превращает программу в тренировки подопечного на конкретные дни.',
    ),
    spot(
      's1-build',
      t.beat('s1-build', 6) + 40, // четыре таблицы, связи и знак вопроса уже на месте
      end('s1-build') - 14,
      MODEL_BOX,
      'Модель данных',
      'Четыре таблицы: упражнения, шаблоны с упражнениями по неделям, тренировки и записанные подходы. Стрелка — связь: шаблон берёт упражнения из библиотеки, подход принадлежит тренировке и упражнению из её плана. Открытый вопрос — что хранит тренировка: ссылку на шаблон или свою копию плана. Пусть ИИ объяснит схему простыми словами, а решите вы.',
    ),
    spot(
      's2-pitfall',
      t.beat('s2-pitfall', 4) + 90, // ссылки нарисованы, присед удалён вместе с подходами Анны
      t.beat('s2-pitfall', 5) + 30,
      LINK_BOX,
      'Ссылка вместо копии',
      'Здесь тренировка хранит только номер шаблона и показывает план из него, а подход ссылается на упражнение плана — то есть на строку шаблона. Правка шаблона переписывает историю всех подопечных, а удаление строки с каскадом (onDelete: cascade) стирает записанные подходы. С библиотекой так же: сделанное упражнение лучше убрать в архив, чем удалить.',
    ),
    spot(
      's2-pitfall',
      t.beat('s2-pitfall', 8) + 90, // обе панели готовы, вопрос и варианты внизу на месте
      end('s2-pitfall') - 14,
      WAYS_BOX,
      'Копия или версия',
      'Копия: при назначении план шаблона переписывают в тренировку, и подходы ссылаются уже на её строки. Версии: шаблон не меняют на месте, а сохраняют новую версию; тренировка и её подходы помнят свою. Оба способа берегут прошлое. Что делать с будущими неделями — оставить или перевести на новый план, — решите сами и запишите в спецификацию.',
    ),
    spot(
      's3-check',
      t.beat('s3-check', 4) + 40, // тест набран целиком, строка требования подсвечена
      t.beat('s3-check', 5) - 6,
      TEST_BOX,
      'Тест на историю',
      'Интеграционный тест: настоящий код и тестовая база, без живых данных. Тестовой подопечной назначают шаблон «Жим лёжа 3×10», записывают подходы, меняют шаблон и снова читают ту же тренировку — план прежний. Второй тест — на удаление: подходы на месте. Новый тест сначала проверьте поломкой: если он не краснеет, он ничего не ловит.',
    ),
  ]
}

