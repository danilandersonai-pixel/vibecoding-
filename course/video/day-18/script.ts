export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-today')
  const s2 = b('s2-build')
  const s3 = b('s3-double')
  const s4 = b('s4-check')
  return {
    's1-today': {
      transition: 'fade',
      camera: [
        // подвальный зал и экран Марины → доска 2: последние 30% и план дня
        key(0, SHOT.whole),
        key(s1(1) - 6, SHOT.whole),
        key(s1(1) + 24, SHOT.board2),
      ],
    },
    's2-build': {
      transition: 'slide',
      camera: [
        // Анна, телефон и сервер крупнее → весь кадр: связь вернулась, отправка и экран Марины (горячая точка)
        key(0, SHOT.s2close),
        key(s2(3) - 6, SHOT.s2close),
        key(s2(3) + 24, SHOT.whole),
      ],
    },
    's3-double': {
      transition: 'zoom',
      camera: [
        // телефон и база крупнее → весь кадр: повтор, номер подхода (горячая точка) → доска 2: конфликт (горячая точка)
        key(0, SHOT.s3close),
        key(s3(2) - 6, SHOT.s3close),
        key(s3(2) + 24, SHOT.whole),
        key(s3(8) - 6, SHOT.whole),
        key(s3(8) + 24, SHOT.board2),
      ],
    },
    's4-check': {
      transition: 'fade',
      camera: [
        // телефон и экран тренера крупнее → весь кадр со списком проверок (горячая точка)
        key(0, SHOT.s4close),
        key(s4(1) - 6, SHOT.s4close),
        key(s4(1) + 24, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-build',
      t.beat('s2-build', 4) + 112, // все три ответа пришли, пометки «отправлено», очередь пуста
      end('s2-build') - 14,
      QUEUE_BOX,
      'Очередь на телефоне',
      'В нашем примере подход сначала ложится в память телефона и встаёт в очередь с пометкой «не отправлено»: закроете приложение — он не пропадёт. Появилась связь — приложение само отправляет очередь по порядку. «Отправлено» загорается только после ответа сервера «принято». Ответа нет — подход остаётся в очереди и уйдёт снова.',
    ),
    spot(
      's3-double',
      t.beat('s3-double', 7) + 24, // повтор пропущен, у всех строк номера, плашка «защита от дублей» на месте
      t.beat('s3-double', 8) - 8,
      ID_BOX,
      'Номер подхода',
      'Номер создаёт телефон в момент записи: это длинная случайная строка, в кадре она укорочена. В базе номер уникален — вторую строку с ним база не пропустит. Повтор сервер не записывает, но отвечает «принято», иначе телефон слал бы его снова. Сравнивать по содержанию нельзя: два одинаковых подхода бывают на самом деле.',
    ),
    spot(
      's3-double',
      t.beat('s3-double', 11) + 112, // две отдельные записи и обе пометки о расхождении на месте
      end('s3-double') - 14,
      SPLIT_BOX,
      'План и подходы — отдельно',
      'В нашем примере план и сделанное хранятся отдельно. План правит только тренер, записанный подход — только подопечный, и правка меняет одну запись по её номеру, так что после связи ничего не затирается. Разошлось сделанное с новым планом — приложение не выбирает молча, а показывает расхождение обоим.',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 6) + 40, // все шесть пунктов отмечены
      end('s4-check') - 14,
      CHECK_BOX,
      'Проверка без интернета',
      'Руками на телефоне: режим полёта, три подхода, перезапуск, связь — и ровно три подхода у тренера. Повтор ловит тест: один и тот же подход с одним номером уходит дважды, а строка в базе одна. Сломайте защиту нарочно — тест обязан покраснеть. Отключённый интернет — та самая странная проверка из главы 3.',
    ),
  ]
}

