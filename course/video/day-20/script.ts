export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-why')
  const s2 = b('s2-build')
  const s3 = b('s3-all')
  const s4 = b('s4-check')
  return {
    's1-why': {
      transition: 'fade',
      camera: [
        // неделя и четыре тренера крупнее → весь кадр: список замечаний
        key(0, SHOT.s1close),
        key(s1(0) + 50, SHOT.s1close),
        key(s1(0) + 80, SHOT.whole),
      ],
    },
    's2-build': {
      transition: 'slide',
      camera: [
        // неразобранный список крупнее → весь кадр со ступенями (горячая точка) → доска 2: круг исправления (горячая точка)
        key(0, SHOT.s2list),
        key(s2(0) + 56, SHOT.s2list),
        key(s2(0) + 86, SHOT.whole),
        key(s2(6) + 40, SHOT.whole),
        key(s2(6) + 74, SHOT.board2),
      ],
    },
    's3-all': {
      transition: 'zoom',
      camera: [
        // просьба «исправь всё» и агент крупнее → весь кадр с большим коммитом → коммит и что было после выкладки (горячая точка)
        key(0, SHOT.s3chat),
        key(s3(1) - 6, SHOT.s3chat),
        key(s3(1) + 24, SHOT.whole),
        key(s3(3) + 20, SHOT.whole),
        key(s3(3) + 56, SHOT.s3after),
      ],
    },
    's4-check': {
      transition: 'fade',
      camera: [
        // что сделать у себя крупнее → весь кадр с очередью (горячая точка — чек-лист)
        key(0, SHOT.s4check),
        key(s4(1) - 6, SHOT.s4check),
        key(s4(1) + 24, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-build',
      t.beat('s2-build', 5) + 76, // все шесть карточек уже на своих ступенях, список слева погас
      t.beat('s2-build', 6) + 40,
      LADDER_BOX,
      'Очередь по тяжести',
      'Четыре ступени — решение нашего примера. Наверху то, из-за чего пропадают данные или их видят чужие: это чинят первым. Ниже — то, что не даёт работать. Потом — то, что раздражает, но обойти можно. Внизу — пожелания: по сути, это новые функции, им место в плане, а не в срочных исправлениях. Чинят по одному, сверху вниз.',
    ),
    spot(
      's2-build',
      t.beat('s2-build', 10) + 50, // все пять шагов круга пройдены, тест зелёный, коммит на месте
      end('s2-build') - 14,
      CYCLE_BOX,
      'Круг одного исправления',
      'Тест повторяет шаги из отчёта об ошибке. Пока беда есть, он красный — значит, ловит её. Агент правит код до зелёного теста, а сам тест не меняет. Правка и тест — один маленький коммит: его легко проверить и откатить, а тест останется и не даст беде вернуться незаметно. «Исправлено» говорит тренер, который её нашёл.',
    ),
    spot(
      's3-all',
      t.beat('s3-all', 6) + 90, // все шесть правок зачёркнуты откатом
      end('s3-all') - 14,
      COMMIT_BOX,
      'Один коммит на всё',
      'Шесть правок в одном коммите не прочесть за 20–30 минут, а новых тестов в нём нет. Сломалось новое — поиск делением пополам приведёт к этому коммиту, но не скажет, какая из шести правок виновата. Откат уберёт все шесть разом, удачные тоже. А главная беда может остаться: её никто не повторил тестом.',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 5) + 60, // все шесть пунктов отмечены
      end('s4-check') - 14,
      CHECK_BOX,
      'Проверьте у себя',
      'Круг на каждое замечание, сверху вниз: шаги до беды, тест по ним — красный, правка кода до зелёного, один коммит, выкладка и проверка у тренера. Следующее — только после его «да». Ясную задачу с готовым тестом можно отдать фоновому агенту, как в день 8: «готово» описано заранее и проверяется тестом.',
    ),
  ]
}

