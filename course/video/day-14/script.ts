export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-today')
  const s2 = b('s2-build')
  const s3 = b('s3-restore')
  const s4 = b('s4-check')
  return {
    's1-today': {
      transition: 'fade',
      camera: [
        // приложение и герои крупнее → весь кадр: колонны надёжности → ближе к колоннам: их не видно, пока не сбой
        key(0, SHOT.s1top),
        key(s1(1) - 6, SHOT.s1top),
        key(s1(1) + 24, SHOT.whole),
        key(s1(2) - 6, SHOT.whole),
        key(s1(2) + 24, SHOT.s1cols),
      ],
    },
    's2-build': {
      transition: 'slide',
      camera: [
        // тесты и скорость (горячая точка — пирамида) → доска 2: ошибка Анны и отчёт крупнее
        // (горячая точка) → вся доска 2 с копиями
        key(0, SHOT.whole),
        key(s2(6) - 6, SHOT.whole),
        key(s2(6) + 24, SHOT.s2errors),
        key(s2(8) - 6, SHOT.s2errors),
        key(s2(8) + 24, SHOT.board2),
      ],
    },
    's3-restore': {
      transition: 'zoom',
      camera: [
        // копии без пробы крупнее → весь кадр с запаской → доска 2: пробное восстановление (горячая точка)
        key(0, SHOT.s3left),
        key(s3(1) - 6, SHOT.s3left),
        key(s3(1) + 24, SHOT.whole),
        key(s3(2) - 6, SHOT.whole),
        key(s3(2) + 28, SHOT.board2),
      ],
    },
    's4-check': {
      transition: 'fade',
      camera: [
        // список и карточки чуть крупнее → весь кадр с вами (горячая точка — список)
        key(0, SHOT.s4close),
        key(s4(4) - 6, SHOT.s4close),
        key(s4(4) + 24, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-build',
      t.beat('s2-build', 2) + 120, // все три яруса пирамиды с подписями на месте
      t.beat('s2-build', 4),
      PYRAMID_BOX,
      'Три уровня тестов',
      'Основание — модульные тесты: их много и они быстрые, проверяют расчёты вроде объёма нагрузки. Выше — интеграционные: код вместе с тестовой базой, например что Дима не откроет тренировки Анны. Вершина — немного сквозных тестов главных сценариев в браузере. Все тесты пишите от требований, а не подгоняйте под готовый код.',
    ),
    spot(
      's2-build',
      t.beat('s2-build', 7) + 70, // сообщение на телефоне и все строки отчёта на месте
      t.beat('s2-build', 8) - 6,
      REPORT_BOX,
      'Отчёт об ошибке',
      'Анна видит короткое понятное сообщение, а подробности уходят вам: экран, что она сделала перед сбоем, полный текст ошибки со стектрейсом, номер подопечной и версия приложения. Ждать, пока Анна напишет Марине, не нужно. Отчёт отдают агенту целиком и просят сначала найти причину — почему упражнение не нашлось, — а не заглушить ошибку.',
    ),
    spot(
      's3-restore',
      t.beat('s3-restore', 8) + 70, // копии, обе базы, оповещение, время и шаги на месте
      end('s3-restore') - 14,
      DRILL_BOX,
      'Пробное восстановление',
      'Это учения: свежую копию поднимают в отдельной тестовой базе, рабочую не трогают. Проверяют то, что точно знают, — вчерашнюю тренировку Анны. Засекают время от начала до конца и записывают шаги. Оповещение о пропущенной ночной копии ловит тихую поломку раньше, чем копия понадобится. Пока проба не прошла, копии считайте непроверенными.',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 4) + 30, // все четыре пункта отмечены, камера стоит
      end('s4-check') - 14,
      LIST_BOX,
      'Проверьте у себя',
      'Тесты: всё зелёное, а нарочно сломанная функция их краснит — значит, они что-то проверяют. Скорость: на медленном экране сначала замер, потом правка по цифрам. Ошибки: тестовый сбой доходит до отслеживания с экраном, шагами и стектрейсом. Копии: вчерашняя копия поднялась в тестовой базе, тренировка Анны на месте, время записано.',
    ),
  ]
}

