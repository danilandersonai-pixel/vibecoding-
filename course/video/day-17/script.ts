export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-today')
  const s2 = b('s2-build')
  const s3 = b('s3-public')
  const s4 = b('s4-check')
  return {
    's1-today': {
      transition: 'fade',
      camera: [
        // весы и Анна крупнее → весь кадр: план дня появляется уже на общем плане
        key(0, SHOT.s1close),
        key(s1(1) - 30, SHOT.s1close),
        key(s1(1), SHOT.whole),
      ],
    },
    's2-build': {
      transition: 'slide',
      camera: [
        // доска 1: замеры → доска 2: фото (горячая точка) → страница Марины и адрес фото крупно
        key(0, SHOT.whole),
        key(s2(3) - 6, SHOT.whole),
        key(s2(3) + 26, SHOT.board2),
        key(s2(6) + 90, SHOT.board2),
        key(s2(6) + 120, SHOT.s2link),
      ],
    },
    's3-public': {
      transition: 'zoom',
      camera: [
        // доска 1: публичная ссылка уходит в чат → доска 2: приватное хранилище (горячая точка)
        key(0, SHOT.whole),
        key(s3(5) - 6, SHOT.whole),
        key(s3(5) + 28, SHOT.board2),
      ],
    },
    's4-check': {
      transition: 'fade',
      camera: [
        // окно проверки крупнее → весь кадр с чек-листом (горячая точка)
        key(0, SHOT.s4win),
        key(s4(1) - 30, SHOT.s4win),
        key(s4(1), SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-build',
      t.beat('s2-build', 5) + 100, // новое фото в хранилище, путь к нему в таблице
      t.beat('s2-build', 6) + 78,
      DATA_BOX,
      'Фото: файл и путь',
      'Фото — файлы, и лежат они в хранилище файлов Supabase, в папке подопечного: 17 — это Анна. В таблице «фото» хранится только путь к файлу — папка и дата снимка. Замеры же — обычные числа в строках таблицы, их закрывает RLS с дня 4. Папка в начале пути пригодится для правила доступа: по ней видно, чьё это фото.',
    ),
    spot(
      's3-public',
      t.beat('s3-public', 8) + 60, // фото удалено, всё остальное на месте
      end('s3-public') - 14,
      PRIVATE_BOX,
      'Приватное хранилище',
      'Так закрыто в нашем примере. Хранилище приватное — постоянных ссылок нет. Правило к папке 17 в Supabase пишут так же, как RLS для таблиц: читают только Анна и её тренер. Им приложение выдаёт подписанную ссылку на 5 минут; открыть её может любой, у кого она есть, но недолго. Удаление стирает и файл, и строку в базе.',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 4) + 130, // все пять проверок отмечены
      end('s4-check') - 14,
      CHECKS_BOX,
      'Проверьте у себя',
      'Пять проверок руками. В панели хранилище не публичное. Адрес фото открывается в окне инкогнито, пока ссылка свежая, а через 5 минут — ошибка. Второй пользователь получает отказ. После удаления файла нет в хранилище, и старая ссылка не открывается. Открылось не тому — чините до запуска, даже если агент уверяет, что всё закрыто.',
    ),
  ]
}

