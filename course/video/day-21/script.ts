export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-build')
  const s2 = b('s2-policy')
  const s3 = b('s3-check')
  const s4 = b('s4-next')
  return {
    's1-build': {
      transition: 'fade',
      camera: [
        // окно со старым адресом крупно → весь кадр: регистратор и проект (горячая точка) → доска 2: страница и политика
        key(0, SHOT.s1browser),
        key(s1(2) - 6, SHOT.s1browser),
        key(s1(2) + 24, SHOT.whole),
        key(s1(4) + 24, SHOT.whole),
        key(s1(4) + 54, SHOT.board2),
      ],
    },
    's2-policy': {
      transition: 'slide',
      camera: [
        // общий шаблон крупнее → весь кадр с данными и Анной → доска 2: политика по своим данным (горячая точка)
        key(0, SHOT.s2template),
        key(s2(2) - 6, SHOT.s2template),
        key(s2(2) + 24, SHOT.whole),
        key(s2(4) - 6, SHOT.whole),
        key(s2(4) + 24, SHOT.board2),
      ],
    },
    's3-check': {
      transition: 'zoom',
      camera: [
        // что сделать у себя крупнее → весь кадр: данные, удаление, телефон → доска 2: чек-листы (горячая точка)
        key(0, SHOT.s3todo),
        key(s3(0) + 40, SHOT.s3todo),
        key(s3(0) + 70, SHOT.whole),
        key(s3(5) - 6, SHOT.whole),
        key(s3(5) + 24, SHOT.board2),
      ],
    },
    's4-next': {
      transition: 'fade',
      camera: [
        // путь 21 дня крупнее → весь кадр: что построено, герои, тест и план (горячая точка)
        key(0, SHOT.s4path),
        key(s4(1) - 6, SHOT.s4path),
        key(s4(1) + 24, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's1-build',
      t.beat('s1-build', 3) + 90, // домен куплен и добавлен, обе записи, сертификат и срок уже на месте
      t.beat('s1-build', 4) + 22,
      DOMAIN_BOX,
      'Свой домен',
      'Какие записи завести у регистратора, подскажет Vercel: обычно запись A — для основного адреса, CNAME — для www. Сертификат https Vercel выпустит сам. Записи заработают не сразу: от минут до 48 часов. Берёте с тренеров плату — нужен платный тариф: Hobby — для личных некоммерческих проектов. В примерах курса мы для краткости писали trener.app.',
    ),
    spot(
      's2-policy',
      t.beat('s2-policy', 5) + 10, // все пять вопросов с ответами уже написаны
      end('s2-policy') - 14,
      POLICY_BOX,
      'Политика по своим данным',
      'Политика — от того, что приложение хранит на деле. Что: имя и почта, тренировки, а вес и замеры, фото и питание — данные о здоровье. Зачем: тренер ведёт подопечного. Кто видит: человек, его тренер и сервисы, куда уходят данные, — скажем, отслеживание ошибок. Где: база и хранилище Supabase. Как удалить — кнопкой. Требования — по закону своей страны.',
    ),
    spot(
      's3-check',
      t.beat('s3-check', 6) + 140, // все статусы стоят: проверки руками отмечены, «не знаю» и «не сделано» закрыты
      end('s3-check') - 14,
      CHECK_BOX,
      'Чек-лист перед первым релизом',
      'Пункты главы 7 и где мы их делали. Ввод проверяет сервер, а не только форма. Запрос сверяет владельца: RLS с дня 4. Секреты — в переменных окружения, а не в коде: за этим следит сканер с дня 6. Ошибка понятна человеку и видна в отслеживании — день 14. Главные пути покрыты сквозными тестами. Копии проверяли в день 14, а откат релиза — ещё нет.',
    ),
    spot(
      's4-next',
      t.beat('s4-next', 2) + 130, // все пять строк плана на месте
      end('s4-next') - 14,
      PLAN_BOX,
      'План на месяц',
      'В нашем примере план — пять строк. Новое берём из отложенных отзывов: тёмную тему просил Олег в день 8, приглашение по номеру ждал Кирилл в бете. Раз в неделю смотрим отслеживание ошибок, раз в месяц пробуем восстановить копию, как в день 14. А одну область сопровождения — обновление библиотек — отдаём агенту на месяц и записываем, что проверили.',
    ),
  ]
}

