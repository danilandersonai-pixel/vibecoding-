export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-cake')
  const s2 = b('s2-ckokf')
  const s3 = b('s3-specific')
  const s4 = b('s4-loop')
  const s5 = b('s5-ask')
  const s6 = b('s6-spec')
  return {
    's1-cake': {
      transition: 'fade',
      camera: [
        // вы, кондитер и торт крупно → весь прилавок с заказом → доска 2: ИИ-стажёр
        key(0, SHOT.s1counter),
        key(s1(2) - 6, SHOT.s1counter),
        key(s1(2) + 24, SHOT.whole),
        key(s1(4) - 6, SHOT.whole),
        key(s1(4) + 26, SHOT.board2),
      ],
    },
    's2-ckokf': {
      transition: 'slide',
      camera: [
        // чат и телефон крупнее → весь кадр с развилками → доска 2: таблица ЦКОКФ (горячая точка)
        key(0, SHOT.s2left),
        key(s2(1) - 6, SHOT.s2left),
        key(s2(1) + 22, SHOT.whole),
        key(s2(2) - 6, SHOT.whole),
        key(s2(2) + 28, SHOT.board2),
      ],
    },
    's3-specific': {
      transition: 'zoom',
      camera: [
        // пробел и «среднее» решение → доска 2: пять правил (горячая точка) → доска 3: коллега
        key(0, SHOT.whole),
        key(s3(1) - 6, SHOT.whole),
        key(s3(1) + 28, SHOT.board2),
        key(s3(5) - 6, SHOT.board2),
        key(s3(5) + 28, SHOT.board3),
      ],
    },
    's4-loop': {
      transition: 'slide',
      camera: [
        // круг уточнений крупнее → весь кадр с отзывом → доска 2: терминал (горячая точка) и правила
        key(0, SHOT.s4loop),
        key(s4(3) - 6, SHOT.s4loop),
        key(s4(3) + 24, SHOT.whole),
        key(s4(5) - 6, SHOT.whole),
        key(s4(5) + 28, SHOT.board2),
      ],
    },
    's5-ask': {
      transition: 'zoom',
      camera: [
        // вопросы перед стартом → доска 2: режим Plan (горячая точка) → доска 3: ещё приёмы
        key(0, SHOT.whole),
        key(s5(4) - 6, SHOT.whole),
        key(s5(4) + 28, SHOT.board2),
        key(s5(6) - 6, SHOT.board2),
        key(s5(6) + 28, SHOT.board3),
      ],
    },
    's6-spec': {
      transition: 'fade',
      camera: [
        // первые два шага крупнее → все четыре шага (горячая точка) → доска 2: пароли и итог
        key(0, SHOT.s6first),
        key(s6(2) - 6, SHOT.s6first),
        key(s6(2) + 24, SHOT.whole),
        key(s6(5) - 6, SHOT.whole),
        key(s6(5) + 28, SHOT.board2),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  const stepsW = 4 * S6.steps.w + 3 * S6.steps.gap
  return [
    spot(
      's2-ckokf',
      t.beat('s2-ckokf', 6) + 20, // все пять строк уже на месте
      end('s2-ckokf') - 14,
      { x: S2.table.x, y: S2.table.y - 8, w: S2.table.w, h: CKOKF_H + 8 },
      'ЦКОКФ',
      'Пять вопросов, на которые стоит ответить до отправки запроса. Цель: что нужно сделать и ради чего. Контекст: в какой части проекта это находится и что там уже готово. Ограничения: что запрещено, а что должно быть непременно. Критерий готовности: по какому признаку видно, что работа закончена. Формат ответа: в какой форме прислать результат. На быстрый вопрос хватит одной фразы; чем крупнее работа и больнее промах, тем больше пунктов расписывайте.',
    ),
    spot(
      's3-specific',
      t.beat('s3-specific', 4) + 72, // пятое правило уже появилось
      t.beat('s3-specific', 5) - 6,
      { x: S3.rules.x, y: S3.rules.y, w: S3.rules.w, h: RULES_H },
      'Пять правил конкретности',
      'Вместо «быстрее» или «красивее» — признак, который можно проверить: время, число, результат. Точный адрес: имя файла, функции, версия программы. Образец: что подаём на вход и что ждём на выходе. Запреты: что трогать нельзя. И по одной задаче за раз: смешаете в сообщении разные просьбы — каждая будет сделана наполовину.',
    ),
    spot(
      's4-loop',
      t.beat('s4-loop', 5) + 100, // все три команды уже в терминале
      end('s4-loop') - 14,
      { x: S4.term.x, y: S4.term.y, w: S4.term.w, h: terminalHeight(TERM_LINES) },
      'Чистый контекст',
      'Когда в разговоре накопилось много неудачных попыток, они мешают: модель снова наступает на те же грабли. Откройте новую сессию и в двух-трёх фразах опишите, что уже выяснили и что не сработало. В Claude Code для этого есть команды: /clear стирает историю и начинает разговор сначала, /compact ужимает длинную историю до короткой сводки, /context показывает, из чего сейчас состоит контекст модели.',
    ),
    spot(
      's5-ask',
      t.beat('s5-ask', 5) + 10, // план написан, ответ пишется
      t.beat('s5-ask', 6) - 6,
      PLAN_BOX,
      'Режим Plan',
      'Отдельный режим в десктопном приложении Claude. В нём Claude только знакомится с проектом и пишет план работ — ни один файл не меняется. Вы читаете план, обычными словами просите что-то убрать или добавить, затем переключаете режим, например на Accept edits, — и лишь тогда начинаются правки файлов. Выбор режима сохраняется только до конца текущей сессии.',
    ),
    spot(
      's6-spec',
      t.beat('s6-spec', 4) + 30, // все четыре шага раскрыты
      t.beat('s6-spec', 5) - 6,
      { x: S6.steps.x - 6, y: S6.steps.y - 6, w: stepsW + 12, h: S6.detailY + S6.detailH - S6.steps.y + 12 },
      'Разработка от спецификации',
      'Работа в четыре шага. Сначала спецификация: что программа должна уметь, без решений о том, как это устроить; правите и утверждаете её вы сами — ещё до появления кода. Затем план: из каких частей будет программа, где хранить данные, в какой последовательности работать и где подстерегают риски. Потом задачи — каждая не больше одного коммита и со своим признаком «готово». Наконец исполнение: задачи уходят агенту по одной, и каждую проверяют, прежде чем браться за следующую.',
    ),
  ]
}

