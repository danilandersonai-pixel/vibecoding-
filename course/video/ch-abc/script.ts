export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-restaurant')
  const s2 = b('s2-parts')
  const s3 = b('s3-git')
  const s4 = b('s4-site')
  const s5 = b('s5-works')
  const s6 = b('s6-ai')
  return {
    's1-restaurant': {
      transition: 'fade',
      camera: [
        // Анна с телефоном → весь ресторан (горячая точка «API»)
        key(0, SHOT.s1near),
        key(s1(1) - 6, SHOT.s1near),
        key(s1(1) + 24, SHOT.whole),
        // ответ доехал — снова к телефону Анны, затем назад к итогу
        key(s1(7) + 50, SHOT.whole),
        key(s1(7) + 80, SHOT.s1near),
        key(s1(8) - 6, SHOT.s1near),
        key(s1(8) + 24, SHOT.whole),
      ],
    },
    's2-parts': {
      transition: 'slide',
      camera: [
        // рецепт и код → проект и библиотеки на доске 2 → наезд на .env
        key(0, SHOT.whole),
        key(s2(3) - 6, SHOT.whole),
        key(s2(3) + 30, SHOT.board2),
        key(s2(6) - 6, SHOT.board2),
        key(s2(6) + 24, SHOT.s2env),
      ],
    },
    's3-git': {
      transition: 'zoom',
      camera: [
        // терминал и сохранения (горячая точка «Коммит») → провал и откат крупно → ветка
        key(0, SHOT.whole),
        key(s3(4) - 6, SHOT.whole),
        key(s3(4) + 24, SHOT.s3pit),
        key(s3(5) - 6, SHOT.s3pit),
        key(s3(5) + 24, SHOT.whole),
        // дифф и пул-реквест на доске 2
        key(s3(6) - 6, SHOT.whole),
        key(s3(6) + 30, SHOT.board2),
      ],
    },
    's4-site': {
      transition: 'slide',
      camera: [
        // терминал и браузер → вниз к окружениям → вправо к деплою
        key(0, SHOT.whole),
        key(s4(2) - 6, SHOT.whole),
        key(s4(2) + 30, SHOT.s4envs),
        key(s4(6) - 6, SHOT.s4envs),
        key(s4(6) + 36, SHOT.board2),
      ],
    },
    's5-works': {
      transition: 'fade',
      camera: [
        // тесты и браузер → панель разработчика крупно (горячая точка) → письмо агенту
        key(0, SHOT.whole),
        key(s5(3) - 6, SHOT.whole),
        key(s5(3) + 24, SHOT.s5dev),
        key(s5(5) + 10, SHOT.s5dev),
        key(s5(5) + 40, SHOT.board2),
      ],
    },
    's6-ai': {
      transition: 'zoom',
      camera: [
        // модель и чат крупнее → весь кадр (токены, действия, MCP) → итог
        key(0, SHOT.s6near),
        key(s6(2) - 6, SHOT.s6near),
        key(s6(2) + 24, SHOT.whole),
        key(s6(6) - 6, SHOT.whole),
        key(s6(6) + 24, SHOT.s6final),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const waiter = ZONES[1]
  const c = S3.commits
  return [
    spot(
      's1-restaurant',
      t.beat('s1-restaurant', 3) + 20, // официант уже вышел
      t.beat('s1-restaurant', 5),
      { x: waiter.x, y: ZONE_TOP, w: waiter.w, h: ZONE_BOTTOM - ZONE_TOP },
      'API — официант',
      'Правила, по которым одна часть приложения просит другую: «сохрани подход», «дай подходы Анны». Через API приложение говорит и с чужими сервисами — оплатой, картами, почтой, ИИ.',
    ),
    spot(
      's3-git',
      t.beat('s3-git', 2) + 75, // флажок «форма подхода» поднят, агент ушёл дальше
      t.beat('s3-git', 4) - 6,
      { x: c.form - 80, y: S3.mainY - 82, w: 160, h: 140 },
      'Коммит',
      'Сохранение с подписью: что и зачем изменили. Вручную — три команды: git status, git add . и git commit -m "подпись". Проще попросить агента.',
    ),
    spot(
      's5-works',
      t.beat('s5-works', 4) + 25, // обе красные строки уже в консоли
      t.beat('s5-works', 5) + 10,
      { x: S5.browser.x + 10, y: S5.browser.y + S5.devTop + 50, w: S5.browser.w - 20, h: 76 },
      'Ошибка в Console',
      'Панель разработчика открывает F12 или Ctrl+Shift+I (на Mac — Cmd+Option+I). Красные строки на вкладке Console — ошибки: скопируйте их текст целиком и отправьте ИИ.',
    ),
  ]
}

const built = buildScript('ch-abc', SCENES, hotspots)

export const chAbcScript = built.script
export const beat = built.beat
export const sceneDuration = (id: string) => built.sceneEnd(id) - built.abs(id, 0)
export const STAGING = staging(built)
