      "Правило «только A–Z» отсекает реальных людей: Ёлкину, O'Connor, Марию-Луизу, Müller. Справедливое начинается с буквы любого алфавита (\\p{L}, \\p{M}), пускает пробелы, дефисы, апострофы и ограничивает длину сотней знаков. Регулярку писать самим не нужно: опишите требование ИИ словами, а до выпуска проверьте форму на именах из разных алфавитов.",
