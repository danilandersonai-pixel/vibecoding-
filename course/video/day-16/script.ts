export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-build')
  const s2 = b('s2-units')
  const s3 = b('s3-check')
  return {
    's1-build': {
      transition: 'fade',
      camera: [
        // места целей, дневника и расчёта чуть крупнее → весь кадр, когда приходит Марина → доска 2: сводка
        key(0, SHOT.s1near),
        key(s1(0) + 100, SHOT.s1near),
        key(s1(1) - 6, SHOT.whole),
        key(s1(5) + 10, SHOT.whole),
        key(s1(5) + 40, SHOT.board2),
      ],
    },
    's2-units': {
      transition: 'slide',
      camera: [
        // дневник с ошибками единиц (горячая точка) → доска 2: белок на двух экранах (горячая точка) и правила
        key(0, SHOT.whole),
        key(s2(5) + 20, SHOT.whole),
        key(s2(5) + 50, SHOT.board2),
      ],
    },
    's3-check': {
      transition: 'zoom',
      camera: [
        // места тестов и агент чуть крупнее → весь кадр к первому тесту: код теста справа, потом неделя
        // и чужой тренер, тесты отмечены (горячая точка)
        key(0, SHOT.s3near),
        key(s3(0) + 90, SHOT.s3near),
        key(s3(1) - 6, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's1-build',
      t.beat('s1-build', 3) + 195, // этикетка, весь расчёт и 210 в строке дневника уже на месте
      t.beat('s1-build', 5) + 10,
      PORTION_BOX,
      'Порция по этикетке',
      'На этикетке калории, белки, жиры и углеводы даны на 100 г. Порция = значение на 100 г × граммы / 100: у овсянки 350 × 60 / 100 = 210 ккал, белки, жиры и углеводы — так же. Дневник хранит граммы и значения на 100 г, а порцию считает код: Анне не нужно ничего пересчитывать в уме.',
    ),
    spot(
      's2-units',
      t.beat('s2-units', 4) + 100, // в форме 1464, у овсянки 878, итог 2124 и «перебор» уже на месте
      t.beat('s2-units', 5) + 16,
      KJ_BOX,
      'Килоджоули вместо калорий',
      '1 ккал = 4,184 кДж, и на пачке часто напечатаны оба числа: у овсянки 350 ккал и 1464 кДж. Вписали кДж в поле «ккал» — порция выросла в 4 с лишним раза: 878 ккал вместо 210. Простая проверка: больше 900 ккал на 100 г не бывает, столько у чистого жира — 9 ккал в грамме. Число выше — повод переспросить.',
    ),
    spot(
      's2-units',
      t.beat('s2-units', 6) + 170, // оба экрана с суммами, отметки и подсветка округлённых строк уже на месте
      t.beat('s2-units', 9) + 40,
      TWO_BOX,
      'Один день — два итога',
      'Экран Анны округлил белок в каждой строке (7,2 → 7, 15,6 → 16, 9,6 → 10) и сложил: 110 г — цель выполнена. Сводка Марины сложила точные числа: 109,4 → 109 г — не добрала. Арифметика верна в обоих местах, а правила разные. Выберите одно — например, точные числа и одно округление итога — и пусть оба экрана зовут одну функцию.',
    ),
    spot(
      's3-check',
      t.beat('s3-check', 7) + 20, // все шесть тестов отмечены, «6 из 6» на месте, камера стоит
      end('s3-check') - 14,
      TESTS_BOX,
      'Тесты на расчёт',
      'Три вида проверок: обычный случай (60 г овсянки — 210 ккал), странный ввод («52,5» с запятой, 1464 в поле «ккал») и пустой ввод — день без записей. Ещё два теста: итог у Анны и у Марины одинаков, а чужой тренер дневник не открывает. Пишите их по правилам, а не по готовому коду.',
    ),
  ]
}

