// id внутри SVG ролика: клипы, градиенты и маркеры. На странице дня смонтировано несколько роликов в одном документе, а
// url(#id) в браузере берёт первый элемент с таким id во всём документе — общий id делает чужой клип, градиент или маркер своим
// (у второго ролика терялась первая цифра номера главы, а наконечники стрелок брали цвет темы страницы). Поэтому в id входит id ролика.
// useId() не годится: он зависит от места в дереве, а рендер Remotion обязан давать одну и ту же разметку на любом кадре и в любом процессе.

/** id для url(#…): «term-<имя>-<id ролика>»; знаки id ролика, которые не годятся в id и селектор, заменяются на «_». */
export function svgId(lessonId: string, name: string): string {
  return `term-${name}-${lessonId.replace(/[^\w-]/g, '_')}`
}
