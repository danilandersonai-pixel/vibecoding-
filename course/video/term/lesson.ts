import type { SessionRecord } from '../sessions/types'
import type { FrameSpec } from './frames'

// Урок как данные (спецификация §6): главы по каркасу (§6.2), в главах — сцены из готовых кадров набора «Репозиторий».
// Время считается из реплик (PACE в kit/script.ts); всё, что меняется в кадре, привязано к номеру реплики (at — с нуля),
// поэтому правка текста не рассинхронизирует картинку. Собирает урок buildLesson (build.ts), проверяет lessonProblems (problems.ts).
//
// Ловушки для автора урока (lessons/<id>/):
// - тест урока зовёт lessonProblems(урок, { minFrames: длина прежнего ролика }) — сама проверка прежней длины не знает;
// - у урока свой снимок сценария script.gen.json: JSON.stringify(buildLesson(урок).script, null, 1) + '\n' через toMatchFileSnapshot,
//   script.ts только читает его (на сайт не попадают записи и код кадров); после правки урока — прогнать тест урока;
// - однострочный Video.tsx урока пробрасывает пропы: (p: { debugSpots?: boolean }) => <LessonVideo lesson={…} {...p} />,
//   иначе lesson-stills.mjs снимет пояснения без рамок;
// - записи сессий урок подключает сам: import s01 from '../../sessions/s01-start.json' и sessions: [s01, s02] as SessionRecord[]
//   (только те, что показывают его кадры); общий video/sessions/index.ts не импортируется — он тянет в ленивый кусок все записи
//   (imports.test.ts следит); сцена со ссылкой на неподключённую запись — проблема урока, а не исключение;
// - у пояснения until = числу реплик (до самого конца) недопустим: последние 12 кадров — смена сцены; без until — до конца минус 12;
//   пояснение с реплики 0 тоже нельзя (она начинается на 9-м кадре);
// - камера и пояснения смотрят на снимок частей конца сцены: у Terminal цель — команда или строка, которую окно не уводит после
//   её появления; сцену, где окно прокручивается, а смотреть нужно на раннее, — разделить;
// - каждые 3–4 с что-то меняется: последняя реплика длиннее ~36 знаков без действия даёт больше 120 кадров до конца сцены.

/** Роль сцены в каркасе: что узнаете, объяснение, пример на записи, типичная ошибка, итог. */
export type Role = 'intro' | 'explain' | 'example' | 'mistake' | 'summary'

export type LessonScene = {
  /** id сцены — уникальный во всём уроке. */
  id: string
  role: Role
  /** Кадр и его данные (frames/index.ts). */
  frame: FrameSpec
  /** Разделы книги сцены — для ссылки в шапке, если сцена из другого раздела, чем глава; без них — разделы главы, потом урока. */
  book?: string[]
  /** Реплики: из них считается время сцены, субтитры и озвучка. */
  lines: string[]
  /**
   * Камера: с реплики at наезд на часть кадра (focusShot; окно кадра не отъезжает от краёв экрана) или весь кадр ('whole'); без ключей —
   * весь кадр. Цель — часть layout кадра (снимок конца сцены); у Terminal — не та, что окно уводит прокруткой.
   */
  camera?: { at: number; target: string | 'whole' }[]
  /**
   * Пояснения по нажатию на часть кадра target: с реплики at (не 0) до реплики until; без until — до конца сцены минус 12 кадров.
   * until = числу реплик означает «до самого конца» и проверкой не пропускается: последние 12 кадров — смена сцены.
   * Камера во время пояснения стоит; прямоугольник после камеры — ниже шапки (y ≥ 88). Цель к открытию уже видна (FrameDef.appears):
   * строка терминала приходит после набора команды, шаг агента — после набора запроса, поэтому пояснение — на реплику позже цели.
   */
  spots?: { at: number; until?: number; target: string; title: string; text: string }[]
  /**
   * Только у сцены mistake: с реплики at в шапке рядом с «Типичная ошибка» — «Неверно» (wrong) или «Верно» (right). Ошибку можно разбить
   * на серию сцен mistake подряд в главе: на всю серию — хотя бы один wrong и один right, wrong раньше (неверный вариант в одной сцене,
   * верный — в следующих). Сцена серии начинается с последнего вердикта прежней: он переходит в шапке без мигания на смене сцен, сцена
   * без своих вердиктов так его и показывает, а свой вердикт того же вида заново не проявляется (sceneVerdict в build.ts, README §1).
   */
  verdict?: { at: number; kind: 'wrong' | 'right' }[]
}

export type LessonChapter = {
  id: string
  /** Название — в шапке кадра, на полосе перемотки и в списке глав плеера. */
  title: string
  /** Разделы книги главы; без них — разделы урока. */
  book?: string[]
  scenes: LessonScene[]
}

/** Урок: проверяется lessonProblems(урок, { minFrames }) в lessons/<id>/lesson.test.ts, сценарий сайта — снимок script.gen.json. */
export type Lesson = {
  /** id ролика: 'ch-abc' — он же id сценария и композиции. */
  id: string
  kind: 'chapter' | 'day'
  title: string
  /** Разделы книги урока: ['sa1', …]. */
  book: string[]
  /**
   * Записи сессий, на которые ссылаются кадры урока: ровно те, что он показывает (сцена со ссылкой на другую запись — проблема урока).
   * Урок импортирует JSON сам, поэтому ленивый кусок ролика несёт только свои записи.
   */
  sessions: SessionRecord[]
  /** Первая глава — «Что узнаете» (у ролика дня — «Что строим сегодня»), последняя — «Итог» («Проверьте у себя»). */
  chapters: LessonChapter[]
}
