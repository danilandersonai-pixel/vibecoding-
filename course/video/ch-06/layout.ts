/** «2 дня», «9 дней», «1 день». */
export function daysWord(n: number): string {
  const ten = n % 10
  const hundred = n % 100
  if (ten === 1 && hundred !== 11) return `${n} день`
  if (ten >= 2 && ten <= 4 && (hundred < 12 || hundred > 14)) return `${n} дня`
  return `${n} дней`
}

