export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-model')
  const s2 = b('s2-question')
  const s3 = b('s3-prompt')
  const s4 = b('s4-tools')
  const s5 = b('s5-loop')
  const s6 = b('s6-decide')
  const s7 = b('s7-traps')
  return {
    's1-model': {
      transition: 'fade',
      camera: [
        // стол с макетом крупно → весь кадр: чего в макете нет → доска 2: прототип — тот же макет
        key(0, SHOT.s1table),
        key(s1(2) - 6, SHOT.s1table),
        key(s1(2) + 24, SHOT.whole),
        key(s1(3) - 6, SHOT.whole),
        key(s1(3) + 28, SHOT.board2),
      ],
    },
    's2-question': {
      transition: 'slide',
      camera: [
        // вопрос и таймбокс → доска 2: тонкий срез и выдуманные данные (горячая точка) → доска 3: выбросить
        key(0, SHOT.whole),
        key(s2(3) - 6, SHOT.whole),
        key(s2(3) + 26, SHOT.board2),
        key(s2(5) - 6, SHOT.board2),
        key(s2(5) + 26, SHOT.board3),
      ],
    },
    's3-prompt': {
      transition: 'zoom',
      camera: [
        // запрос крупно → весь кадр с агентом → доска 2: прототип и список упрощений (горячая точка)
        key(0, SHOT.s3prompt),
        key(s3(1) - 6, SHOT.s3prompt),
        key(s3(1) + 24, SHOT.whole),
        key(s3(3) + 70, SHOT.whole),
        key(s3(3) + 100, SHOT.board2),
      ],
    },
    's4-tools': {
      transition: 'slide',
      camera: [
        // заголовок крупно → конструкторы и холсты (горячая точка) → доска 2: агенты и ноутбуки, правило
        key(0, SHOT.s4title),
        key(s4(1) - 10, SHOT.s4title),
        key(s4(1) + 20, SHOT.whole),
        key(s4(3) - 36, SHOT.whole),
        key(s4(3) - 6, SHOT.board2),
      ],
    },
    's5-loop': {
      transition: 'zoom',
      camera: [
        // цикл крупно → доска 2: показ Марине, скриншот, новый виток → весь кадр: журнал, коммит, выход
        key(0, SHOT.s5cycle),
        key(s5(1) - 6, SHOT.s5cycle),
        key(s5(1) + 26, SHOT.board2),
        key(s5(5) - 6, SHOT.board2),
        key(s5(5) + 26, SHOT.whole),
      ],
    },
    's6-decide': {
      transition: 'fade',
      camera: [
        // два вопроса крупно → всё дерево с исходами → доска 2: прототип и продакшен (горячая точка)
        key(0, SHOT.s6top),
        key(s6(0) + 50, SHOT.s6top),
        key(s6(0) + 78, SHOT.whole),
        key(s6(4) - 6, SHOT.whole),
        key(s6(4) + 26, SHOT.board2),
      ],
    },
    's7-traps': {
      transition: 'zoom',
      camera: [
        // демо и 70/30 → доска 2: ключ API (горячая точка) → доска 3: база, настоящие данные, спагетти
        key(0, SHOT.whole),
        key(s7(1) + 4, SHOT.whole),
        key(s7(1) + 34, SHOT.board2),
        key(s7(3) - 6, SHOT.board2),
        key(s7(3) + 26, SHOT.board3),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-question',
      t.beat('s2-question', 3) + 96, // срез прошёл все три слоя, путь подписан
      t.beat('s2-question', 5) - 6,
      S2.sliceSpot,
      'Тонкий срез',
      'Один сценарий, доведённый до конца через все слои приложения: экран, логику и данные. Всего остального может пока не быть. Десять нарисованных экранов без работающего пути не покажут, жива ли идея, а один пройденный путь — покажет: человек проходит его сам, и вы видите, где он споткнулся.',
    ),
    spot(
      's3-prompt',
      t.beat('s3-prompt', 4) - 10, // список уже на доске 2, камера стоит
      end('s3-prompt') - 14,
      { x: S3.simple.x - 8, y: S3.simple.y - 8, w: S3.simple.w + 16, h: SIMPLE_H + 16 },
      'Список упрощений',
      'Последняя строка шаблона просит ИИ честно перечислить, что в прототипе сделано «на скорую руку». Данные в памяти — после выключения всё пропадает. Входа и разграничения прав нет. Подопечные выдуманы, тестов нет. Если прототип решат развивать, этот перечень и есть список задач перед продакшеном.',
    ),
    spot(
      's4-tools',
      t.beat('s4-tools', 2) + 44, // карточка холстов заполнена
      t.beat('s4-tools', 3) - 42, // до отъезда камеры к карточкам 3–4
      { x: S4.cards[1] - 6, y: S4.cardY - 6, w: S4.cardW + 12, h: S4.cardH + 12 },
      'Claude Design',
      'Холст Anthropic для макетов: вы рисуете будущие экраны и сценарий, но настоящего кода за ними нет. С октября 2026 года Claude Design уже не бета и есть даже на бесплатном тарифе. Он живёт прямо в чате и в Claude Code, поэтому готовый макет можно сразу отдать агенту — пусть соберёт по нему страницу.',
    ),
    spot(
      's6-decide',
      t.beat('s6-decide', 5) + 20, // все шесть строк таблицы на месте
      end('s6-decide') - 14,
      { x: S6.table.x - 6, y: S6.table.y - 6, w: S6.table.w + 12, h: TABLE_H + 12 },
      'Прототип и продакшен',
      'Шесть различий. Данные: у прототипа они в памяти или выдуманы, у продукта — настоящая база, миграции и резервные копии. Доступ: вход общий или его нет — против ролей, прав и защиты от перебора паролей. Ошибки: прототип просто перезапускают, а продукт их обрабатывает, повторяет попытку и понятно объясняет. Тесты: почти никаких — против модульных, интеграционных и сквозных. Наблюдение: вывод в консоль — против журналов, показателей и оповещений о сбоях. Выкладка: руками или кнопкой — против CI/CD, нескольких окружений и отката.',
    ),
    spot(
      's7-traps',
      t.beat('s7-traps', 2) + 40, // сервер с ключом и файл .env на месте
      t.beat('s7-traps', 3) - 6,
      S7.safeSpot,
      'Ключ на сервере',
      'Всё, что есть в странице, видно в браузере: панель разработчика открывается у любого. Поэтому страница обращается к вашему серверу, а уже он идёт в сервис и подставляет ключ — до браузера ключ не доходит. В самом коде ключа нет: код берёт его из переменной окружения. На вашем компьютере значение лежит в файле .env, на хостинге — в настройках проекта. Файл .env записан в .gitignore, так что Git его не сохраняет и в репозиторий он не уходит.',
    ),
  ]
}

