export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-why')
  const s2 = b('s2-plan')
  const s3 = b('s3-like')
  const s4 = b('s4-check')
  return {
    's1-why': {
      transition: 'fade',
      camera: [
        // Марина и Дима крупнее → весь кадр: новый тренер, запуск и «сначала немногие»
        key(0, SHOT.s1close),
        key(s1(1) - 6, SHOT.s1close),
        key(s1(1) + 24, SHOT.whole),
      ],
    },
    's2-plan': {
      transition: 'slide',
      camera: [
        // план крупнее → весь кадр: список замечаний и наблюдение (горячая точка — план)
        key(0, SHOT.s2plan),
        key(s2(4) - 6, SHOT.s2plan),
        key(s2(4) + 24, SHOT.whole),
      ],
    },
    's3-like': {
      transition: 'zoom',
      camera: [
        // «нравится?» и пустое замечание → доска 2: задача, телефон и журнал (горячая точка) → доска 1: замечание
        key(0, SHOT.whole),
        key(s3(2) - 6, SHOT.whole),
        key(s3(2) + 24, SHOT.board2),
        key(s3(6) + 24, SHOT.board2),
        key(s3(6) + 54, SHOT.whole),
      ],
    },
    's4-check': {
      transition: 'fade',
      camera: [
        // что сделать у себя крупнее → весь кадр со списком замечаний (горячая точка)
        key(0, SHOT.s4check),
        key(s4(4) - 6, SHOT.s4check),
        key(s4(4) + 24, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  const end = (id: string) => t.sceneEnd(id) - t.abs(id, 0)
  return [
    spot(
      's2-plan',
      t.beat('s2-plan', 4) + 30, // камера отъехала, план дописан: кто, срок, три задачи
      end('s2-plan') - 14,
      PLAN_BOX,
      'План бета-теста',
      'В нашем примере план помещается на одной карточке. Кто: четыре тренера, которые приложение ещё не видели, — коллеги со стороны, а не друзья. Срок: неделя обычной работы. Задачи: три настоящих дела из их дня. Задача — это действие, которое тренер делает сам, а не вопрос «как вам?».',
    ),
    spot(
      's3-like',
      t.beat('s3-like', 5) + 122, // все четыре пометки, вопрос и ответ уже записаны
      t.beat('s3-like', 6) + 24,
      JOURNAL_BOX,
      'Журнал наблюдения',
      'Пока тренер решает задачу, вы молчите и коротко записываете, что видите: куда нажал, где остановился, что искал. Время у пометок показывает, где заминка была дольше всего. Подскажи вы — и этой заминки в записи бы не было. После задачи — один вопрос: что человек ожидал увидеть. Ответ подскажет, каким сделать экран.',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 4) + 140, // все четыре строки в списке, включая сбой из отслеживания
      end('s4-check') - 14,
      LIST_BOX,
      'Список замечаний',
      'Одна таблица на всех, как отзывы в день 8. В строке — кто, какая задача, где застрял и что ожидал увидеть, словами тренера. Это те же части хорошей обратной связи из главы 2: действие, ожидание и результат. Сбои из отслеживания ошибок — тоже сюда, как строка Ксении.',
    ),
  ]
}

