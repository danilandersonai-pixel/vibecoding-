export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-intro')
  const s2 = b('s2-pain')
  const s3 = b('s3-copy')
  const s4 = b('s4-check')
  return {
    's1-intro': {
      transition: 'fade',
      camera: [
        // эталон Б и ваше приложение крупнее → весь кадр: у эталона А всё то же
        key(0, SHOT.s1near),
        key(s1(0) + 96, SHOT.s1near),
        key(s1(0) + 132, SHOT.whole),
      ],
    },
    's2-pain': {
      transition: 'slide',
      camera: [
        // отзывы и стопки (горячая точка), тренеры → доска 2: маленький срез
        key(0, SHOT.whole),
        key(s2(7) - 6, SHOT.whole),
        key(s2(7) + 24, SHOT.board2),
      ],
    },
    's3-copy': {
      transition: 'zoom',
      camera: [
        // список «как у них» и гонка за эталоном (горячая точка) → доска 2: боль Марины → назад к списку
        key(0, SHOT.whole),
        key(s3(5) - 6, SHOT.whole),
        key(s3(5) + 24, SHOT.board2),
        key(s3(6) - 6, SHOT.board2),
        key(s3(6) + 24, SHOT.whole),
      ],
    },
    's4-check': {
      transition: 'fade',
      camera: [
        // что сделать у себя и срез → доска 2: спецификация и таблица паритета (горячая точка) → показ тренерам
        key(0, SHOT.whole),
        key(s4(4) - 6, SHOT.whole),
        key(s4(4) + 24, SHOT.board2),
        key(s4(5) + 48, SHOT.board2),
        key(s4(5) + 78, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  return [
    spot(
      's2-pain',
      t.beat('s2-pain', 4) + 100, // все шесть жалоб в стопках, счёт, «у вас уже есть» и следующая стопка уже отмечены
      t.beat('s2-pain', 6),
      PILES_BOX,
      'Стопки жалоб',
      'В одну стопку кладут жалобы про одно и то же, даже если люди говорят по-разному: «не видит, что сделал» и «скидываю скриншоты» — про одну боль. Просьбы о функциях вроде тёмной темы тоже записывают, но смотрят на высоту стопки. Самая высокая у вас уже закрыта — берите следующую и сверяйте её со своими тренерами.',
    ),
    spot(
      's3-copy',
      t.beat('s3-copy', 3), // обе полосы и подпись «гонка без финиша» уже на месте
      t.beat('s3-copy', 5) - 6,
      RACE_BOX,
      'Гонка за эталоном',
      'У зрелого эталона сотни функций, и копил он их годами. Повторять всё подряд — значит вечно догонять. Важнее главные сценарии и одно своё отличие, прочее подождёт. О каждой функции эталона решите: берём, меняем или откладываем — отличие как раз в «меняем». А прежде чем переносить функцию, спросите: зачем она здесь?',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 4) + 112, // спецификация, все строки таблицы и оба отличия уже на месте
      t.beat('s4-check', 5) + 48,
      TABLE_BOX,
      'Отличие в таблице паритета',
      'В таблице паритета у каждой возможности эталона своё решение: готово, наше отличие, позже или не делаем. «Тренер видит подходы» — отличие, которое у вас уже есть. «Правка на тренировке» — новое: его срез вы строите сегодня. Остальные функции эталонов тоже попадают в таблицу, но с решением, а не сразу в работу.',
    ),
  ]
}

