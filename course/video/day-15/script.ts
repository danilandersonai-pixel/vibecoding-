export type Staging = { transition: Transition; camera: CameraKey[] }

type Shot = { x: number; y: number; zoom: number }
const key = (at: number, shot: Shot): CameraKey => ({ at, ...shot })

// Переход и камера каждой сцены: камера едет к тому, о чём реплика, и стоит, пока открыта горячая точка.
function staging({ beat }: Timing): Record<string, Staging> {
  const b = (id: string) => (i: number) => beat(id, i)
  const s1 = b('s1-today')
  const s2 = b('s2-first')
  const s3 = b('s3-empty')
  const s4 = b('s4-check')
  return {
    's1-today': {
      transition: 'fade',
      camera: [
        // Марина, Дима и знакомое меню крупнее → весь кадр: Ира и план дня
        key(0, SHOT.s1close),
        key(s1(1) - 6, SHOT.s1close),
        key(s1(1) + 24, SHOT.whole),
      ],
    },
    's2-first': {
      transition: 'slide',
      camera: [
        // регистрация крупнее → весь кадр: первый экран и «всё сразу» (горячая точка) → доска 2: полировка
        key(0, SHOT.s2close),
        key(s2(1) - 6, SHOT.s2close),
        key(s2(1) + 24, SHOT.whole),
        key(s2(4) - 6, SHOT.whole),
        key(s2(4) + 26, SHOT.board2),
      ],
    },
    's3-empty': {
      transition: 'zoom',
      camera: [
        // белый лист крупнее → весь кадр: списки с данными, Ира уходит, последние 30% → доска 2: исправление (горячая точка)
        key(0, SHOT.s3close),
        key(s3(1) - 6, SHOT.s3close),
        key(s3(1) + 24, SHOT.whole),
        key(s3(5) - 6, SHOT.whole),
        key(s3(5) + 28, SHOT.board2),
      ],
    },
    's4-check': {
      transition: 'fade',
      camera: [
        // дела и пустые списки крупнее → доска 2: доступность (горячая точка) → доска 1 целиком: показ новому человеку
        key(0, SHOT.s4close),
        key(s4(2) - 6, SHOT.s4close),
        key(s4(2) + 24, SHOT.board2),
        key(s4(6) - 6, SHOT.board2),
        key(s4(6) + 26, SHOT.whole),
      ],
    },
  }
}

type Rect = { x: number; y: number; w: number; h: number }

function hotspots(t: Timing): VideoHotspot[] {
  const cams = staging(t)
  // Окно точки — в кадрах сцены; рамка объекта на холсте переводится в кадр по камере в начале окна.
  const spot = (id: string, from: number, to: number, r: Rect, title: string, text: string): VideoHotspot => {
    const s = toScreen(r, cameraAt(from, cams[id].camera))
    return { from: t.abs(id, from), to: t.abs(id, to), x: Math.round(s.x), y: Math.round(s.y), w: Math.round(s.w), h: Math.round(s.h), title, text }
  }
  return [
    spot(
      's2-first',
      t.beat('s2-first', 2) + 100, // первый экран, «всё сразу» с пометками «пусто» и рамка у кнопки на месте
      t.beat('s2-first', 3) + 24,
      FIRST_BOX,
      'Первый экран нового тренера',
      'Новичок ещё ничего не знает о приложении. В нашем примере первый экран здоровается и предлагает одно действие, без которого остальное пусто: тренеру нужен подопечный, значит — приглашение. Разделы на месте, но программы, рекорды и отчёты без данных ничего не покажут, поэтому не стоит вываливать их на человека сразу.',
    ),
    spot(
      's3-empty',
      t.beat('s3-empty', 6) + 96, // оба исправленных экрана и три подписи нарисованы
      t.beat('s3-empty', 7) + 40,
      EMPTY_BOX,
      'Пустой экран с подсказкой',
      'Пустой список видит каждый новый пользователь, а ИИ о нём часто забывает. В нашем примере у пустого экрана три части: что здесь будет, что сделать сейчас и кнопка, которая сразу ведёт к этому действию. Экран тренировок ведёт к «Назначить», экран подопечных — к приглашению по ссылке. Откройте так каждый свой список.',
    ),
    spot(
      's4-check',
      t.beat('s4-check', 4) + 160, // клавиатура, порядок фокуса, контраст и подписи — всё на месте
      t.beat('s4-check', 5) + 130,
      A11Y_BOX,
      'Проверка доступности',
      'Клавиатура: Tab ведёт фокус к следующему полю, Enter нажимает кнопку, рамка фокуса видна и идёт сверху вниз. Контраст: текст хорошо читается на своём фоне, бледное на светлом не годится. Подписи: у кнопки-значка есть название — его зачитает скринридер. ИИ может проверить это сам, но итог смотрите своими глазами.',
    ),
  ]
}

