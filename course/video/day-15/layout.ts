// Крупный телефон рисуется прямо в координатах холста (без масштаба), поэтому текст на экране
// пишется обычным размером, не мельче 18 px.
export const HAND = { w: 300, h: 420, side: 10, top: 30, bottom: 16 }

/** Экран телефона с левым верхним углом (x, y): прямоугольник внутри рамки. */
export function screenOf(p: { x: number; y: number; w?: number; h?: number }): Rect {
  const w = p.w ?? HAND.w
  const h = p.h ?? HAND.h
  return { x: p.x + HAND.side, y: p.y + HAND.top, w: w - 2 * HAND.side, h: h - HAND.top - HAND.bottom }
}

/** Строка влезает в ширину экрана крупного телефона: оценка ширины знака — 0,56 размера шрифта. */
export function fitsScreen(text: string, size: number, pad = 32): boolean {
  return text.length * size * 0.56 <= HAND.w - 2 * HAND.side - pad
}

