// Ролик набора «Репозиторий» — кадр 1920 × 1080 и всегда тёмный; старые ролики — 1280 × 720 и светлые.
// Единственный признак тёмного кадра в плеере: по нему фон сцены, рамки пояснений и размер сообщения об ошибке.
export function isTermScript(script: { width: number }): boolean {
  return script.width === 1920
}
